/**
 * Чи відповідав на `/api/*` справді канвас.
 *
 * Чистий модуль — ні DOM, ні fetch: сюди приходять уже зняті поля відповіді.
 *
 * НАВІЩО. На порту канваса періодично піднімається сторонній процес (у власника
 * двічі — `python -m http.server 8765`, батько launchd). IPv6-сокет виграє в
 * `localhost`, і застосунок отримує від нього 404-HTML **із кодом 200** для
 * кореня. Далі `res.json()` падає на розборі, а повідомлення складається так,
 * ніби не читаються НАШІ файли: «tasks.json не читається», «граф не
 * завантажився». Дизайнер за такою підказкою йде чинити валідний `tasks.json`
 * і нічого там не знаходить — інструмент звинуватив невинного.
 *
 * Перевіряємо ТИП, а не вміст: `_send_json` у `serve.py` ставить
 * `application/json` завжди, тож будь-що інше на `/api/*` означає, що
 * відповідав не канвас. Тип, а не «чи розібрався JSON», бо чужа сторінка може
 * випадково виявитись валідним JSON-ом, а наш обробник — ні, і тоді причина
 * знову з'їхала б не туди.
 *
 * @param {{ok: boolean, status: number, contentType: ?string}} res
 * @returns {?string} ключ i18n для причини, або `null`, якщо відповідь наша.
 */
export function apiProblem({ ok, contentType }) {
  // Не-ok розбирає той, хто кликав: там уже є і код, і текст помилки нашого
  // сервера. Назвати 500 «зайнятим портом» означало б підмінити одну хибну
  // підказку іншою.
  if (!ok) return null;
  const type = String(contentType || "").split(";")[0].trim().toLowerCase();
  return type === "application/json" ? null : "tasksErrPort";
}
