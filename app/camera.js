/**
 * Камера канваса: чиста математика пану, зуму й перельоту до кадру. Ні DOM, ні
 * rAF — вони в app.js.
 *
 * Одна ощущалка на все. Раніше колесо застосовувало трансформ мгновенно, а
 * `animateT()` із CSS-переходом `.4s ease` лежав мертвим кодом — тобто не згладжено
 * було нічого. Тепер ЧЕРЕЗ ЦІЛЬ їдуть колесо і переліт до кадру (`camTo` + `step`);
 * «вписати все» і ресайз ставлять камеру НАПРЯМУ і навмисно: миттєвий snap на
 * завантаженні доречніший за анімацію.
 *
 * Викликачів `camTo` тепер ДВА — колесо і клік по рядку панелі сторінок
 * (`focusBox`), — тож `camStop()` на авторитетних стрибках (рука на драгу,
 * «вписати все») стереже вже не теоретичний випадок: цикл, що доїжджає до кадру,
 * інакше пише поверх щойно порахованої камери.
 */
import { t } from "./i18n.js";

export const MIN_SCALE = 0.05;
/* Підлога САМЕ ДЛЯ «вписати все». Окрема від `MIN_SCALE` навмисно: у тих двох
   чисел різна робота. `MIN_SCALE` не дає макету зникнути під рукою, коли людина
   крутить колесо. А «вписати все» мусить ВПИСАТИ — і якщо для цього потрібен
   масштаб дрібніший за колісну підлогу, то потрібен. Виміряно на демо-задачі
   (сторінка висотою 8000px, світ 18079px): на вікні 804px вписування лишало 54px
   за краєм, на 654px — 129px, і масштаб в усіх випадках стояв на 0.05. Полотно
   мовчки показувало менше, ніж є. */
export const FIT_MIN_SCALE = 0.008;
export const MAX_SCALE = 2.5;

/** Стеля «вписати все» — НЕ `MAX_SCALE`: кадр знято 1:1, збільшувати його нема сенсу,
 *  а видно це мусить бути з експортів файла, а не з тіла функції. */
export const FIT_MAX_SCALE = 1;

/** Максимальна дельта колеса за подію. Тачпадний пінч і інерційний скрол
 *  видають сотні за раз — без клампа зум стрибав одним рухом у межу. */
export const MAX_WHEEL_DELTA = 120;

/** Час, за який лишається ~37% відстані. МОДУЛЬНА константа, не параметр:
 *  відкритий параметр дозволив би одному викликові тихо завести свою ощущалку — рівно
 *  те, заради прибирання чого цей модуль існує. */
const TAU_MS = 90;

export const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

/** Клітинок сітки квантування на подвоєння масштабу. Вісім — це крок ~9%, тобто
 *  відхилення кегля до 4.5%: на 22px це 1px, якого не побачити. */
export const SCALE_QUANT = 8;

/**
 * Масштаб, посаджений на грубу сітку — рівно для CSS-змінної на `#world`, з якої
 * рахується кегль підпису смуги (`calc()`).
 *
 * Навіщо квантувати, коли можна писати сам масштаб: змінна на `#world`
 * УСПАДКОВУЄТЬСЯ, тож кожен її запис інвалідує стиль усім кадрам, смугам і
 * підписам світу. Спека попередила про це разом із самим рішенням, тому писати
 * її можна лише при РЕАЛЬНІЙ зміні значення — а «реальна» без сітки означає
 * «щокадру»: згладжування камери міняє масштаб на мільйонні частки навіть на
 * хвості, коли на екрані вже нічого не рухається.
 *
 * Сітка МУЛЬТИПЛІКАТИВНА, а не крок у сотих: масштаб живе між 0.05 і 2.5, і
 * рівномірний крок був би або грубим у низу діапазону (де 0.01 — це п'ята
 * частина зуму), або зайво дрібним у верху. Октава ділиться на `SCALE_QUANT`
 * рівних частин, тобто відносна точність однакова на всьому діапазоні.
 */
export function quantScale(scale) {
  /* Той самий контракт, що в `zoomAt`: нуль і NaN до `calc()` доходити не сміють.
     Кегль став би `Infinity`/`NaN`, браузер викинув би недійсне оголошення — і
     підпис лишився б без розміру зовсім, без жодної скарги в консолі. */
  if (!Number.isFinite(scale) || scale <= 0) {
    throw new Error(t('camQuantScaleInvalid', scale));
  }
  return 2 ** (Math.round(Math.log2(scale) * SCALE_QUANT) / SCALE_QUANT);
}

/** Підсилення щипка трекпада: він приходить як `wheel` з `ctrlKey` і крихітним `deltaY` (1–10), а колесо — 100. */
export const PINCH_GAIN = 6;
const LINE_PX = 16;

/** Колесо в «Огляді» (0.25.0, як у Figma): ⌘/Ctrl + колесо і щипок — масштаб, просто колесо / два пальці — рух. */
export function wheelIntent(e, viewH) {
  const k = e.deltaMode === 1 ? LINE_PX : e.deltaMode === 2 ? viewH : 1;
  if (e.ctrlKey || e.metaKey) return { kind: "zoom", delta: e.deltaY * k * (e.ctrlKey && !e.metaKey ? PINCH_GAIN : 1) };
  return { kind: "pan", dx: (e.deltaX || 0) * k, dy: (e.deltaY || 0) * k };
}

/** Зсунути камеру на (dx, dy) пікселів екрана. */
export const panBy = (cam, dx, dy) => ({ x: cam.x - dx, y: cam.y - dy, scale: cam.scale });

/**
 * Крок згладжування до цілі. `dt` у мілісекундах, тому крок не залежить від
 * частоти кадрів: на 120Hz рух не стає вдвічі швидшим.
 */
export function step(cur, target, dt) {
  // Ціль мусить мати скінченні координати, інакше цикл буде вічним
  for (const key of ["x", "y", "scale"]) {
    if (!Number.isFinite(target[key])) {
      throw new Error(t('camTargetInvalid', key, target[key]));
    }
  }
  const k = 1 - Math.exp(-Math.max(dt, 0) / TAU_MS);
  const next = {
    x: cur.x + (target.x - cur.x) * k,
    y: cur.y + (target.y - cur.y) * k,
    scale: cur.scale + (target.scale - cur.scale) * k,
  };
  const settled = Math.abs(target.x - next.x) < 0.5
    && Math.abs(target.y - next.y) < 0.5
    && Math.abs(target.scale - next.scale) < 0.0005;
  // Доїхали — сідаємо РІВНО в ціль, інакше лишається дрібний хвіст, який
  // тримає rAF-цикл живим назавжди.
  return settled ? { ...target, done: true } : { ...next, done: false };
}

/** Зум навколо курсора: світова точка під курсором лишається під курсором. */
export function zoomAt(cam, { cx, cy, delta }) {
  // Нульовий масштаб дав би Infinity у перерахунку центра. Досяжним він зараз не є
  // (усі шляхи запису йдуть через клампи), але контракт мусить це гарантувати сам.
  if (!Number.isFinite(cam.scale) || cam.scale <= 0) {
    throw new Error(t('camZoomScaleInvalid', cam.scale));
  }
  const d = clamp(delta, -MAX_WHEEL_DELTA, MAX_WHEEL_DELTA);
  const scale = clamp(cam.scale * Math.exp(-d * 0.0016), MIN_SCALE, MAX_SCALE);
  const k = scale / cam.scale;
  return { x: cx - (cx - cam.x) * k, y: cy - (cy - cam.y) * k, scale };
}

/** Вписати світ у вьюпорт із полем. Не збільшуємо понад 1: кадр 1:1 — межа. */
export function fitBox(box, view, pad = 60) {
  const w = Math.max(box.w, 1);
  const h = Math.max(box.h, 1);
  const scale = clamp(Math.min((view.w - pad * 2) / w, (view.h - pad * 2) / h),
                      FIT_MIN_SCALE, FIT_MAX_SCALE);
  return { x: (view.w - w * scale) / 2, y: (view.h - h * scale) / 2, scale };
}

/**
 * Камера, за якої ВИДНО й ЧИТНО один кадр: клік по рядку панелі сторінок.
 *
 * Масштаб — по ШИРИНІ кадру, і це не спрощення. Кадр знято макетом 1280px
 * завширшки, а висота в нього буває 8000px: вписаний по габариту (`fitBox`) він
 * дав би той самий bird-view, з якого людина й тікає, натискаючи рядок. Тому
 * `box.h` тут не потрібен зовсім — і не перевіряється: сторожити поле, якого
 * функція не читає, було б театром.
 *
 * По горизонталі кадр по центру, а його ВЕРХ — на `pad` нижче верхнього краю:
 * дизайнер хоче побачити початок екрана. Вертикальне центрування у високого
 * кадру відрізало б рівно цей початок.
 *
 * Межі масштабу ті самі, що в решти камери, і стеля та сама, що у «вписати все»
 * (`FIT_MAX_SCALE`): кадр знято 1:1, роздувати його понад 1 нема чого.
 *
 * @param {{x:number, y:number, w:number}} box кадр у СВІТОВИХ координатах
 * @param {{w:number, h:number}} view габарит полотна
 */
export function focusBox(box, view, pad = 60) {
  /* Падати мусимо ТУТ і синхронно. `step` ціль теж стереже, але кидає вже
     всередині rAF-кадру: хендл циклу лишається непорожнім, наступний `camTo` не
     запускає нічого, і камера мертва до перебудови холста — а в консолі помилка
     без жодного натяку, хто цю ціль поставив. */
  for (const key of ["x", "y", "w"]) {
    if (!Number.isFinite(box[key])) {
      throw new Error(t('camFrameInvalid', key, box[key]));
    }
  }
  /* Ширина нулем — вироджений вхід (кадр завжди 1280px), але охорона тут не
     декоративна: у ПАРІ з полотном, не ширшим за поля, вона дає `0 / 0`, а
     `clamp` від NaN вертає NaN — і ціль камери стає непридатною. Сам по собі
     нуль у нормальному полотні дає `Infinity`, який кламп зрізає до стелі; це
     виміряно мутаційно, щоб охороні не приписувалась чужа заслуга. */
  const w = Math.max(box.w, 1);
  const scale = clamp((view.w - pad * 2) / w, MIN_SCALE, FIT_MAX_SCALE);
  return {
    x: view.w / 2 - (box.x + w / 2) * scale,
    y: pad - box.y * scale,
    scale,
  };
}
