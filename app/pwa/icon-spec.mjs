/**
 * Специфікація значків застосунку «Deai Canvas» — ОДНЕ місце, з якого беруть і
 * генератор (`make-icons.mjs`), і тест (`tests/pwa.test.mjs`).
 *
 * Навіщо окремо від генератора. Генератор тягне Playwright і запускає браузер,
 * тож тест не може його імпортувати. А без спільного джерела тест і генератор
 * мали б по власній копії «яким кольором і де лежить логотип» — і розійшлись би
 * мовчки: значки перемалювали б, тест лишився б зеленим на старій геометрії.
 *
 * Не `.js` навмисно: це інструмент збірки, не код застосунку, і під охоронців
 * `app/**` (i18n, парсинг, керуючі байти) він не потрапляє — там нічого з цього
 * не буває. Спільний із застосунком лише `logo.js`, який генератор читає.
 */

/** Кольори — ті самі токени оболонки, що малюють логотип у смузі:
 *  фон = `--s1`, рамка = `--logo` (`--g400`), внутрішній прямокутник = `--logo-in`.
 *  Літерали, а не читання `styles.css`, бо генератору потрібне значення, а не
 *  каскад; збіг фону з `--s1` стереже тест. */
export const PALETTE = { bg: "#29332E", frame: "#969F9A", inner: "#FFFFFF" };

/** Файли значків: розмір і призначення — рівно те, що заявляє маніфест. */
export const ICON_FILES = [
  { file: "icon-192.png", size: 192, purpose: "any" },
  { file: "icon-512.png", size: 512, purpose: "any" },
  { file: "icon-maskable-512.png", size: 512, purpose: "maskable" },
];

/** Сторона логотипа як частка сторони значка. 0.55 обрано з безпечної зони
 *  maskable: ОС може обрізати значок колом діаметра 80% сторони, а найдальша
 *  точка квадрата логотипа — його кут, тобто пів-діагоналі 0.55/2·√2 ≈ 0.389
 *  мусить влізти в радіус 0.4. Одна частка на обидва призначення — щоб `any` і
 *  `maskable` не виглядали як два різні значки. */
export const LOGO_FRACTION = 0.55;

/** Скруглення `any`-значка як частка сторони. `maskable` — без скруглення: маску
 *  накладає ОС, і прозорий кут дав би їй «рамку» чужого кольору. */
export const CORNER_FRACTION = 0.225;

/**
 * Розкладка значка заданого розміру й призначення.
 * @returns {{logo: number, offset: number, radius: number}} сторона логотипа,
 *   відступ квадрата логотипа від краю (за обома осями) і радіус скруглення, px.
 */
export function layoutOf(size, purpose) {
  const logo = Math.round(size * LOGO_FRACTION);
  return {
    logo,
    offset: (size - logo) / 2,
    radius: purpose === "maskable" ? 0 : Math.round(size * CORNER_FRACTION),
  };
}
