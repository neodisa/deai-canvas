/** Підтримувані мови інтерфейсу, у порядку типовості: українська — типова. */
export const LANGS = ["uk", "en"];

/** Словники за мовою; ключ — елемент `LANGS`. */
export const DICT = { uk: UK, en: EN };

/** Ключ, під яким мова лежить у `localStorage` (сам запис/читання — за `app.js`). */
export const LANG_KEY = "dc-lang";

let lang = "uk";

/** Поточна мова інтерфейсу. */
export const getLang = () => lang;

/**
 * Перемикає поточну мову. Невідому мову відкидає тут, а не мовчки приймає:
 * інакше розсинхрон із `DICT` спливає не на виклику `setLang`, а сирим
 * TypeError на першому ж `t()`.
 */
export function setLang(next) {
  if (!LANGS.includes(next)) throw new Error(`i18n: невідома мова «${next}»`);
  lang = next;
}

/**
 * Значення зі сховища → придатна мова. Усе незрозуміле (`null`, чужий рядок,
 * мова, яку прибрали з `LANGS`) — українська: інструмент не має падати через
 * значення, що лежало в `localStorage` з іншої версії словника.
 */
export const readStoredLang = (raw) => (LANGS.includes(raw) ? raw : "uk");

/**
 * Переклад ключа поточною мовою. Значення-функція викликається з аргументами,
 * переданими після `key`, — так у рядок влітає число чи назва.
 */
export function t(key, ...args) {
  const v = DICT[lang][key];
  if (v === undefined) throw new Error(`i18n: немає ключа «${key}»`);
  return typeof v === "function" ? v(...args) : v;
}
