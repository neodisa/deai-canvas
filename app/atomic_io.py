"""Атомарний запис JSON і спільний лок писарів стану design-canvas.

Окремий лист-модуль (тільки stdlib), а не функція всередині `serve`, з двох
причин. Перша: `pages_model` теж пише стан, а імпортувати звідти `serve` не
можна — залежність спрямована serve → pages_model, і зворотний імпорт замкнув
би цикл. Спільний лист розвʼязує це без циклу і прибирає третю копію патерну.
Друга, важливіша: два незалежні локи в двох модулях одне одного НЕ бачать, тож
лок мусить жити там, куди дотягуються обидва.
"""
import json
import os
import stat
import tempfile
import threading

# Суфікс недописаного файла. Спільна константа, а не літерал у кожного писаря:
# `serve._is_tool_junk` відсіює саме його з відбитка макета, з експорту колегам
# і зі штампа зʼємки. Розійдуться — осиротілі tmp тихо повернуться в спільне
# репо (регресія 28.08.2026).
TMP_SUFFIX = '.tmp'

# Один лок на процес для писарів стану: `serve.save_tasks`, `serve.save_meta`,
# `pages_model.write_pages`. Сервер — ThreadingHTTPServer, тобто два запити
# справді йдуть паралельно, а кожен із цих писарів робить ДВА кроки: копію в
# `.bak` і сам запис. Лок склеює їх в один, тож `.bak` лишається рівно одним
# кроком назад, а не двома.
#
# ⚠️ Чого цей лок НЕ дає: він не рятує від втрати правки при read-modify-write.
# Виклик виглядає як `cfg = load_tasks(); cfg[...] = ...; save_tasks(cfg)`, і
# ЧИТАННЯ лишається ЗЗОВНІ лока — другий потік прочитає до запису першого і
# затре його правку. Саме так губилось `vercel_project` (інцидент 03.08.2026).
#
# Для `pages.json` цю ваду ЗАКРИТО, але не цим локом: читання-зміну-запис
# огортає `pages_model.pages_lock` (міжпроцесний flock) або `pages_model.mutate`
# (лок + перевірка rev + запис), і ходять саме через них обробники `serve.py`,
# що пишуть в ІСНУЮЧУ ітерацію. Створення нової ітерації і
# `_pages_from_iterations` пишуть у нову теку, якої ще ніхто не читає, — лока
# там нема, і це не діра. `WRITE_LOCK` лишається лише для склейки `.bak` із
# записом.
#
# Для `tasks.json` і `iterations.json` вада ЛИШАЄТЬСЯ ВІДКРИТОЮ: `save_tasks` і
# `save_meta` у викликачів досі стоять після читання, зробленого поза локом.
# Не пиши ніде, що інцидент 03.08.2026 полагоджено, поки лок не охопить читання
# разом із записом у кожного їхнього викликача.
#
# Звичайний Lock, не RLock, і це навмисно: жоден писар під локом не кличе
# іншого, тож повторний захват означав би саме те, чого ми не хочемо — вкладену
# пару, яку ніхто не планував. Хай краще вона стане видимим дедлоком.
WRITE_LOCK = threading.Lock()


def atomic_write_json(path, data, indent=2):
    """Записати JSON так, щоб КРАШ ПРОЦЕСУ не лишив обрізаного файла.

    Саме краш процесу, не втрата живлення: `fsync` тут свідомо немає. На macOS
    чесний скид на пластину вимагає `F_FULLFSYNC` (звичайний fsync драйв може
    збрехати), і платити цим на кожен чих полотна ми не готові. Після паніки
    ядра чи зникнення струму файл може виявитись порожнім — це визнана межа.

    mkstemp + os.replace у ТІЙ САМІЙ теці: через межу файлової системи rename
    перестає бути атомарним і деградує до копіювання. Тимчасовий файл ВЛАСНИЙ
    на кожен виклик — спільне імʼя зводило б атомарність нанівець, бо два
    потоки відкрили б один шлях і обрізали одне одного.

    ⚠️ Права на цілі: якщо ціль була read-only (0444), запис ТЕПЕР пройде —
    міняється не файл, а запис у теці, і прав на сам файл для цього не треба.
    Старий `open(path, 'w')` на такому файлі падав із PermissionError. Якщо
    колись знадобиться шанувати read-only як «заморожено», перевіряти це треба
    явно, а не сподіватись на побічний ефект способу запису.
    """
    # Симлінк розіменовуємо: старий `open(path, 'w')` писав НАСКРІЗЬ, а
    # `os.replace` бʼє по самому лінку й мовчки перетворив би його на звичайний
    # файл. Конфіг, який користувач навмисно виніс кудись і залінкував, тихо
    # відʼєднався б від справжнього місця. Побічно це ще й обовʼязкова умова
    # атомарності: тека береться від СПРАВЖНЬОГО файла, а не від лінка, який
    # може лежати на іншій файловій системі.
    path = os.path.realpath(path)
    d = os.path.dirname(path) or '.'
    fd, tmp = tempfile.mkstemp(dir=d, prefix=os.path.basename(path) + '.',
                               suffix=TMP_SUFFIX)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=indent)
        # Режим ЦІЛІ, а не той, що дав mkstemp. mkstemp створює 0600, і
        # os.replace переносить цей режим на ціль, затираючи режим старого
        # файла — тобто перший же запис після оновлення зробив би tasks.json/
        # iterations.json/pages.json owner-only. Старий open(path, 'w') режим
        # наявного файла зберігав, і мовчки міняти права на файлах користувача
        # інструмент не має права. chmod ДО replace: ціль не мусить і мигнути
        # чужим режимом. Файла ще не було — лишаємо 0600 від mkstemp: своїх
        # прав не розширюємо, а вгадувати umask у потоковому сервері нічим
        # (os.umask глобальний на процес і сам по собі гонка).
        try:
            os.chmod(tmp, stat.S_IMODE(os.stat(path).st_mode))
        except FileNotFoundError:
            pass
        os.replace(tmp, path)
    except BaseException:
        # BaseException, а не Exception, і це НЕ перестраховка: Ctrl-C посеред
        # json.dump — це і є «убитий прогін», заради якого весь цей модуль.
        # KeyboardInterrupt і SystemExit не успадковують Exception, тож із
        # вужчим except вони пронесли б tmp повз прибирання, і кожне переривання
        # лишало б по файлу — тим гірше, що імʼя в кожного власне.
        try:
            os.remove(tmp)
        except OSError:
            pass
        raise
