/**
 * Чиста модель смуги: три зони, контроли в них, причини недоступності,
 * яруси зникнення. Модуль віддає ДАНІ — масиви обʼєктів із `id`/`tier`/
 * `whyKey`... — а не HTML. Збірку DOM робить План B; тут ні розмітки, ні
 * i18n (причини — це ІМЕНА ключів словника, рядком, а не переклад: `t()`
 * кличе вже DOM-шар, за патерном `app/viewport.js` і `app/flow-model.js`).
 *
 * Чому цей модуль існує: живий інструмент має смугу фіксованої ширини
 * 1462px, яка не стискається — на 1440 зрізає 22px, на 1280 — 182, на
 * 1024 — 438, і кнопка публікації з посиланням на превью просто їдуть за
 * екран. Коли нову смугу проєктували в прототипі (`docs/proto/shell.html`),
 * модель ЖИЛА в HTML-шаблонах, і це дало ще два дефекти, і обидва знайшли
 * не читанням коду, а виміром у браузері:
 *
 *   1. На 1024 підписи ховались контейнерним запитом, а заміна («⋯») не
 *      зʼявлялась — керування виглядом ставало НЕДОСЯЖНИМ ЗОВСІМ. Тобто
 *      контрол не був ні в смузі, ні в переповненні — він зникав.
 *   2. Головна кнопка публікації стискалась у 20-піксельний обрубок: підпис
 *      ховався, а іконки в опублікованому стані не було. «Присутня в DOM»
 *      не означає «нею можна скористатись».
 *
 * Винісши модель сюди, обидва дефекти стають юніт-тестами (`visibleAt` /
 * `overflowAt` покривають кожен контрол на кожному ярусі, `icon` у публікації
 * перевіряється в кожному стані) — вони біжать за мілісекунди й ловлять
 * регресію одразу, а не наступним прогоном Playwright.
 *
 * Три зони — не оформлення, а відповідь на три різні питання: зона 1 «де
 * я» (крошки), зона 2 «як дивлюсь» (режим і все, що від нього залежить),
 * зона 3 «куди віддаю» (GitLab і публікація). Контрол, який не належить
 * жодній, — привід переглянути контрол, а не додати четверту зону.
 *
 * Статус Клода — в острівці внизу робочої області (`claude-status.js`), не в
 * смузі: на вузькому вікні фішка з'їдала крихти задачі й ітерації.
 */

import { hasPublish, isLegacyPublish } from "./spaces-model.js";

/**
 * Яруси зникнення в зоні 2, ширина вікна в пікселях. Значення підтверджені
 * прототипом (`docs/proto/shell.html`, секція «СМУГА: три зони»): `gl` і
 * `mode` — це пороги, на яких зникає ПІДПИС (лишається сама іконка), `view` —
 * поріг, на якому зникає ВЕСЬ контрол (переїжджає в «⋯»).
 */
export const TIERS = { gl: 1300, mode: 1180, view: 1060 };

/* Раніше тут був спільний набір «контролів назовні» (`gl` + `publish`), які разом зникали з простору
   без інтеграцій (`integrations === false`). З модулями 2а їх розщеплено: GitLab лишився на
   `integrations`, а публікація пішла на `hasPublish` (`capabilities.publish`) — простір без інтеграцій
   публікує вбудованим модулем у теку (див. `barModel`, «Вимикач»). */

/**
 * Причина, з якої «Флоу» недоступний у сегменті «Сітка/Флоу». Три РІЗНІ
 * стани, і ревʼю Task 8 (п.2) попросило записати їх явно — бо їх сплутали
 * один раз, і без цього списку сплутають знову:
 *
 *   1. Перелік сторінок узагалі не прийшов (`pagesError`) — рано казати
 *      щось про `flow.json`: ми ще НЕ ЗНАЄМО, чи він є, бо базові дані самі
 *      не завантажились. Найвищий пріоритет.
 *   2. `flow.json` нема зовсім (`flowRaw` falsy, `flowError` порожній) —
 *      контрол вимкнений, причина «немає файла».
 *   3. `flow.json` Є, але не читається — побитий JSON (`flowRaw` falsy,
 *      `flowError` непорожній) — контрол вимкнений, причина ІНША: файл є,
 *      але з нього нічого не побудувати.
 *   4. `flow.json` прочитався, граф ПОБУДОВАНИЙ (`flowRaw` truthy) — причини
 *      НЕМА, і контрол ЖИВИЙ, НАВІТЬ якщо в графі лишились скарги парсингу
 *      (висячі вузли, дублі id, кільця — рахує `flow-model.js`). Скарги —
 *      це не «зламаний флоу», це нормальний робочий стан: граф є, показує
 *      свої проблеми на полотні. `flowRaw` head каже правду про ЦЕЙ виклик;
 *      `flowError`, якщо він тут є, — залишок ПОПЕРЕДНЬОЇ невдалої спроби,
 *      не сигнал про поточний граф.
 */
export function flowWhyKey(s) {
  if (s.pagesError) return "whyPagesError";
  if (!s.flowRaw) return s.flowError ? "whyFlowBroken" : "whyNoFlow";
  return "";
}

/**
 * Причина, з якої посилання на превью недоступне. Порядок пріоритету
 * несучий: «задача не опублікована» важливіша за «ітерація не в превью», бо
 * перше робить друге неважливим — без публікації взагалі немає превью, куди
 * ітерація могла б потрапити.
 */
export function linkWhyKey(s) {
  if (!s.published) return "whyNoPublish";
  /* Пароль змінено, а зібране превʼю ще зі старим: посилання з `#k=<новий>`
     менеджеру НЕ відкриє превʼю. Вище за «ітерація не в превʼю» — бо стосується
     будь-якої ітерації. */
  if (s.pwStale) return "whyPwStale";
  if (!s.iterPub) return "whyItOff";
  if (!s.pagePub) return "whyPageOff";
  return "";
}

/** Пункт «Сповіщати Teams» зі стану `/api/teams-mute`. */
export function teamsItem(tm) {
  const base = { id: "teamsnotify", labelKey: "teamsNotify" };
  if (!tm) return { ...base, on: false, disabled: true, whyKey: "whyTeamsLoading" };
  if (tm.error) return { ...base, on: false, disabled: true, whyKey: "whyTeamsUnknown" };
  return { ...base, on: !tm.muted, disabled: false, whyKey: "",
    subKey: tm.muted ? (tm.mine ? "teamsMutedByMe" : "teamsMutedSub") : "teamsOnSub",
    subArgs: tm.muted ? [] : [tm.channel || ""] };
}

/**
 * Причина, з якої «В Figma» недоступна. Порядок несучий: в «Огляді» кадри —
 * знімки, живого DOM немає ЗОВСІМ, тож «немає ітерації» чи «уже копіюю» там
 * лише відволікали б від справжньої причини. Спільна для смуги й ⌘K
 * (`shell-palette.js`) — друга копія розійшлася б із першою.
 */
export function figmaWhyKey(s) {
  if (s.mode === "overview") return "whyFigmaOverview";
  if (!s.hasIteration) return "whyFigmaNoMockup";
  if (s.figmaBusy) return "whyFigmaBusy";
  return "";
}

/* Смуга помилки «tasks.json не читається» — спільна для звичайного складу й
   екрана «Задачі»: помилка читання списку стосується ОБОХ, і ховати її там, де
   список задач якраз і є сенсом екрана, було б найгіршим місцем для мовчання. */
function tasksError(s) {
  return s.tasksErr
    ? { whyKey: s.tasksErrKey || "tasksErr", retry: true }
    : null;
}

/**
 * Побудова трьох зон смуги зі стану екрана `s`. Кожен контрол — обʼєкт з
 * `id` (унікальний у межах усієї смуги) і `tier` (ярус, на якому ВЕСЬ
 * контрол ховається в «⋯»; `0` — ніколи). `labelTier`, де є, — ярус, на
 * якому ховається лише підпис, а іконка лишається.
 */
export function barModel(s) {
  // Крошка ітерації існує лише коли ітерація Є — «задача без ітерацій» це
  // реальний старт кожної нової задачі (ревʼю Task 8, п.7), і крошка не
  // повинна стояти бляклою чи вимкненою: як «Флоу»/інспектор, вона зникає.
  // Мітки поруч із підписом (п.5): `pub` — зелена крапка «в превью» (те саме
  // `iterPub`, що керує посиланням), `onGl` — хмара «ця ітерація збігається
  // з GitLab».
  /* Палітра стоїть ПЕРЕД крошками, і це свідомий компроміс, а не недогляд.
     Вона не відповідає на питання жодної з трьох зон («де я» / «як дивлюсь» /
     «куди віддаю») — вона відповідає на четверте, «що я взагалі можу». Власне
     місце для неї — окрема колонка сітки перед зоною 1, але сітка смуги це
     `minmax(0,1fr) auto minmax(0,1fr)`, і четверта колонка збила б ЦЕНТРУВАННЯ
     зони 2: перемикач режимів поїхав би вліво від середини вікна. Ціна голови
     зони 1 нижча — трохи менше місця крошкам (це міряє інваріант «крошку
     стиснуло браком місця») проти зламаної геометрії всієї смуги.

     Чому вона взагалі мусить бути видимою: до 02.09.2026 палітра жила ТІЛЬКИ
     на ⌘K. Власник шукав її словами «поиск по функционалам, куда-то он делся,
     потерялся» — тобто з його боку вона й була втрачена, разом із перемикачем
     мови, який ми туди свідомо сховали. Схована дія без дверей — це не
     схована дія, а зникла. */
  /* Логотип — ПЕРШИЙ, перед палітрою (батч 1.52): він відповідає на «де я і
     як вийти до всіх задач», а це старший рівень за «що я можу». Той самий
     компроміс щодо трьох зон, що й у палітри (див. вище): окремої колонки не
     заводимо. `on` — «зараз відкритий екран Задачі», з нього розмітка бере
     підсвітку. */
  const home = { id: "home", tier: 0, on: !!s.homeOpen };
  const palette = { id: "palette", tier: 0, labelTier: TIERS.mode };
  /* Фішка простору (Deai 1.0, етап 1) — «де я» ще на рівень вище за задачу:
     задача живе в просторі, тож шлях читається зліва направо, і фішка стоїть
     ПЕРЕД крошкою задачі (і на екрані «Задачі», де крошка — «Задачі»). `s.space`
     нема, коли шар просторів вимкнено чи просторів ще нема, — тоді фішки НЕМАЄ
     в моделі, а не стоїть порожньою: смуга така, як була до просторів. `color` —
     токен (`space-1…6`); у стилі його робить розмітка, там же його й валідує. */
  const spaceChip = s.space
    ? [{ id: "space", tier: 0, label: s.space.name, color: s.space.color }]
    : [];

  /* Екран «Задачі» — склад смуги змінюється ЦІЛКОМ тут, а не приховуванням у
     розмітці: модель описує склад, розмітка його малює. Принцип 5 PRODUCT.md
     (контрол, безглуздий у цьому режимі, прихований): без задачі перед очима
     нема що публікувати, перемикати між «Макет/Огляд» чи вантажити в Figma.
     Принцип 3 (головна дія не зникає) тримається: головна дія тут — «назад до
     задачі». Зони лишаються трьома (порожні масиви): грид смуги на них
     тримається, і зона 2 порожня не зсуває нікого — вона `auto`. Без `taskId`
     «Назад» вести нікуди, тож його немає, а не мертвий. */
  if (s.homeOpen) {
    const zone1 = [home, palette, ...spaceChip, { id: "crumb-tasks", tier: 0, labelKey: "tasks" }];
    if (s.taskId) zone1.push({ id: "back", tier: 0, label: s.taskId });
    return { zone1, zone2: [], zone3: [], error: tasksError(s) };
  }

  const zone1 = [
    home,
    palette,
    ...spaceChip,
    { id: "task", tier: 0, label: s.taskId },
  ];
  if (s.hasIteration) {
    /* `items` — ПЕРЕЛІК ітерацій, а не лише поточна. Без нього дропдаун несе
       самі дії, і обрати НЕ-останню ітерацію в інструменті стає нічим: у
       `app.js` `picked` інакше встановлюється тільки на останню, на щойно
       створену, або скидається. Для менеджера ітерацій це втрата основної
       функції — знайдено після того, як панельний `<select>` прибрали, а
       заміни в моделі не виявилось. */
    /* `author`/`mine`/`origin` їдуть ДАНИМИ, а не готовим підписом: складати
       «Іт.6 · Ольга» тут означало б робити це мовою збірки, а мову вибирає
       глядач (`i18n.js`). `mine !== false` — бо ітерація БЕЗ підпису своя:
       вся історія до появи авторів не сміє раптом стати чужою. */
    zone1.push({
      id: "iter", tier: 0, label: s.iterLabel, note: s.iterNote,
      pub: !!s.iterPub, onGl: !!s.iterOnGl,
      author: s.iterAuthor || "", mine: s.iterMine !== false,
      origin: s.iterOrigin || null,
      items: (s.iterList || []).map((x) => ({
        id: x.id, label: x.label, note: x.note || "",
        pub: !!x.pub, onGl: !!x.onGl, on: x.id === s.iterId,
        author: x.author || "", mine: x.mine !== false, origin: x.origin || null,
      })),
    });
  }

  const zone2 = [
    {
      id: "mode", tier: 0, labelTier: TIERS.mode, value: s.mode,
      items: [
        { id: "layout", labelKey: "modeLayout" },
        { id: "overview", labelKey: "modeOverview" },
      ],
    },
  ];

  // Перемикач «Сітка/Флоу» існує лише в «Огляді» — у «Макеті» дивляться на
  // живий макет, а не на кадри, і перемикати їх немає чого.
  if (s.mode === "overview") {
    const flowWhy = flowWhyKey(s);
    zone2.push({
      // labelTier: TIERS.mode — ревʼю Task 8 (п.1): у прототипі `.lbl-mode`
      // вішається на ВСІ сегменти зони 2 (`segBtn`), і контейнерний запит
      // ховає їх ОДНИМ правилом на 1180. Модель, що памʼятала цей ярус лише
      // в `mode`, брехала б про «Сітка»/«Флоу»: сказала б «підпис видно» там,
      // де CSS уже його прибрав.
      id: "view", tier: 0, labelTier: TIERS.mode, value: s.view,
      items: [
        { id: "grid", labelKey: "viewGrid" },
        {
          id: "flow", labelKey: "viewFlow",
          disabled: !!flowWhy, whyKey: flowWhy,
        },
      ],
    });
  }

  zone2.push({
    id: "vp", tier: TIERS.view, value: s.vp,
    // Довільна ширина вводиться лише в «Макеті» — в «Огляді» кадри вже
    // зняті під фіксовані пресети, свого поля там нема.
    showCustom: s.mode === "layout", vpw: s.vpw,
    items: [
      { id: "desktop", labelKey: "vpDesktop" },
      { id: "tablet", labelKey: "vpTablet" },
      { id: "mobile", labelKey: "vpMobile" },
    ],
  });

  // Інспектор працює по живому DOM макета, якого в «Огляді» не існує —
  // там кадри це знімки. Тому контрол зникає, а не стоїть ввімкненим і
  // нічого не робить.
  if (s.mode === "layout") {
    zone2.push({
      id: "inspector", tier: TIERS.view, labelTier: TIERS.mode,
      labelKey: "inspector", active: s.right === "inspector",
    });
  }

  // Дропдаун GitLab (ревʼю Task 8, п.4): чотири розгалуження, не два.
  // «off» — репозиторій не підключений, нема з чим працювати, крім
  // «Налаштувати» (ні «Надіслати», ні історії). Інакше — «Підтягнути»
  // зʼявляється лише при «behind»; «Надіслати» є завжди, вимкнене з
  // причиною лише при «sync» (уже збігається, надсилати нічого); історія —
  // завжди, коли репозиторій узагалі підключений.
  const glItems = s.gl === "off"
    ? [{ id: "glsetup", labelKey: "glSetup" }]
    : [
      ...(s.gl === "behind" ? [{ id: "glpull", labelKey: "glPull", subKey: "glPullSub" }] : []),
      {
        id: "glpush", labelKey: "glPush",
        disabled: s.gl === "sync", whyKey: s.gl === "sync" ? "glSync" : "",
      },
      { id: "glhistory", labelKey: "glHistory" },
    ];

  const linkWhy = linkWhyKey(s);
  const figmaWhy = figmaWhyKey(s);
  /* Вимикач інтеграцій (спека просторів, розділ «Вимикач») і публікація модулем (спека 2а).
     Два РІЗНІ питання, і розщепив їх Task 8 модулів:
       · `noInteg` — простір, де `integrations === false`: він не має GitLab, Teams-каналу
         задачі й командного каналу — вони ходять назовні (git push, дашборд команди), а там цього
         нема. Рівно `=== false`, а не «нема значення»: простір без відомостей (стара форма
         відповіді, шар вимкнено) не має красти в людини GitLab.
       · `hasPublish` — чи є в просторі ХТОСЬ, хто публікує: зашитий код ЛІГА (`'legacy'`) або
         модуль (`static-publish`, локальна тека, нічого назовні). Без інтеграцій публікує модуль, тож
         кнопка «Опублікувати» там ЖИВА. `capabilities.publish === null` (модуль вимкнено) — публікації
         нема, і вона ЗНИКАЄ з моделі, а не стоїть мертвою кнопкою: причина «публікувати нічим» не
         лікується кліком.
     «В Figma» лишається завжди — вона працює по живому макету. */
  const noInteg = s.space?.integrations === false;
  const legacy = isLegacyPublish(s.space);
  /* Підпис «локально» — дані (ключ + аргументи), а не готовий текст: мову вибирає глядач. Лише для
     ЛОКАЛЬНОЇ публікації (`pubLocal`, її каже `previewTarget` в `app.js`). */
  const localSub = (key, args = []) => (s.pubLocal ? { subKey: key, subArgs: args } : {});
  const publishItems = [
    { id: "togglepub", labelKey: "showInPreview", on: !!s.iterPub },
    {
      id: "openpreview", labelKey: "openPreview",
      disabled: !s.published, whyKey: s.published ? "" : "whyNoPublish",
      ...localSub("publishLocalSub", [s.pubWhen || ""]),
    },
    {
      id: "copylink", labelKey: "copyLink",
      disabled: !!linkWhy, whyKey: linkWhy,
      ...localSub("publishLocalLinkSub"),
    },
    /* Тиша Teams на канал задачі (батч 1.52). Невідомо (ще вантажиться чи
       база недосяжна) — пункт вимкнений З ПРИЧИНОЮ: показати «увімкнено»
       навмання — та сама брехня, від якої тиша мусить бути видимою.
       Лише з інтеграціями: без них `app.js` тримає `teams: null` ВІЧНО (стану
       тиші немає, `/api/teams-mute` там відповідає 409), і пункт висів би
       вічним «перевіряю стан у базі…». З інтеграціями `null` — коротка мить
       завантаження, і саме для неї причина й потрібна. */
    ...(noInteg ? [] : [teamsItem(s.teams)]),
    /* Пароль превʼю (ідея 02.09.2026). НЕ вимикається ніколи: задати пароль
       до першої публікації — нормальний порядок. `warnKey` — «новий пароль
       ще не в превʼю», це попередження, а не причина вимкнення. Лише ЛІГА: у
       модуля свій пароль — секрет, якого UI не знає (`spaces-model.js`, `pwView`). */
    ...(legacy ? [{
      id: "pubpw", labelKey: "pubPw", pw: s.pw || "",
      subKey: s.pwCustom ? "pubPwCustom" : "pubPwDefault",
      warnKey: s.pwStale ? "pubPwStale" : (s.pwUngated ? "pubPwUngated" : ""),
      warnArgs: s.pwUngated ? [s.pwUngated] : [],
    }] : []),
  ];
  /* Застереження модуля «за адресою» (Vercel, 2b-1): `s.pubGate`/`s.pubGateStale` — те, що віддав сервер
     (`publish_gate`/`publish_gate_stale`, `app.js` лише переказує). РІВНО булеві: поле не прийшло (`undefined`) —
     мовчимо, а не лякаємо. Лише для МОДУЛЯ: у ЛІГА своє застереження (`pubGateTruth`, розмітка), і її попередження
     про сталість пароля — `pubPw*` — живуть в іншому місці; а там, де публікує модуль «у теку», сервер цих полів не дає.
     Дані (`id` + ключ), а не текст: мову вибирає глядач (`shell-bar.js`). */
  const notes = legacy ? [] : [
    ...(s.pubGate === false ? [{ id: "public", key: "publishPublicWarn" }] : []),
    ...(s.pubGateStale === true ? [{ id: "stale", key: "publishGateStale" }] : []),
  ];
  const zone3 = [
    /* «В Figma» (T-41) — ПЕРЕД GitLab, щоб головна кнопка публікації лишалась
       крайньою справа (рішення власника 28.09.2026). В «Огляді» не зникає, як
       інспектор, а стоїть вимкненою з причиною: зона 3 не сміє стрибати при
       кожному перемиканні режиму. */
    /* `iconOnly` в «Огляді»: там кнопка однаково вимкнена, а зона 2 ширша на
       «Сітка/Флоу» — з підписом зона 3 не влазила на 1360 (живий
       `shell.test.mjs`, рішення власника 28.09.2026). GitLab і публікація при
       цьому не зсуваються: зона 3 притиснута вправо. */
    {
      id: "figma", tier: 0, labelTier: TIERS.gl, labelKey: "toFigma",
      iconOnly: s.mode === "overview",
      busy: !!s.figmaBusy, disabled: !!figmaWhy, whyKey: figmaWhy,
    },
    ...(noInteg ? [] : [{
      id: "gl", tier: 0, labelTier: TIERS.gl,
      labelKey: "gitlab", status: s.gl, items: glItems,
    }]),
    ...(hasPublish(s.space) ? [{
      id: "publish", tier: 0,
      // Іконка є ЗАВЖДИ, у кожному стані — саме тут живий інструмент ставав
      // 20-піксельним обрубком: підпис ховався, а іконки не було.
      icon: s.pubStale ? "warn" : "up",
      published: !!s.published, stale: !!s.pubStale,
      /* Чий це постачальник: розмітка ховає застереження про «публічне ЛІГА-посилання»
         (`pubGateTruth`) там, де публікує модуль. */
      legacy,
      notes,
      labelKey: s.published ? "update" : "publish",
      items: publishItems,
    }] : []),
  ];

  // Стан «tasks.json не читається» (ревʼю Task 8, п.6): у прототипі
  // (`renderBar`) під трьома зонами зʼявляється смуга помилки з причиною й
  // кнопкою «Спробувати ще». Це не зона і не контрол смуги — четверте поле,
  // окремо від `zoneN`, тому воно не бере участі в перевірці унікальності id.
  // `tasksErrKey` — ПРИЧИНА, `tasksErr` — сам факт помилки. Дві величини, два
  // поля: коли на порту відповідає чужий процес, факт той самий, а причина
  // зовсім інша, і типовий текст відправляв би чинити невинний `tasks.json`.
  const error = tasksError(s);

  return { zone1, zone2, zone3, error };
}

/* Ярус 0 — «не ховається ніколи». Порівняння НЕ суворе: контрол із tier=1060
   на ширині рівно 1060 уже в «⋯» — саме так поводяться контейнерні запити,
   бо `max-width:1060px` матчиться НА 1060. Розбіжність тут дала б модель, що
   розходиться з CSS на рівно один піксель — найгірший вид неузгодженості. */
const hidden = (item, w) => item.tier > 0 && w <= item.tier;
export const visibleAt = (zone, w) => zone.filter((x) => !hidden(x, w));
export const overflowAt = (zone, w) => zone.filter((x) => hidden(x, w));
export const labelVisibleAt = (item, w) => !(item.labelTier > 0 && w <= item.labelTier);
