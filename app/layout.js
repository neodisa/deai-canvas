/**
 * Розкладка карток канваса. Чисті функції: ні DOM, ні fetch, ні location —
 * тому тестується в node (`tests/layout.test.mjs`).
 *
 * Ряд заввишки під найвищу карточку В НЬОМУ, а не в усьому світі. Раніше висота
 * була одна на всі картки (максимум по вмісту), і коротка сторінка стояла
 * пустим простирадлом на висоту найдовшої статті.
 *
 * Нарізка плоского переліку по числу колонок жила тут до 31.08.2026 і прибрана
 * разом із сітковим виглядом «по три»: ряд задає модель (`app/rows-model.js`), а
 * два тіла з тією самою формулою розійшлися б на першій же правці.
 */
import { t } from "./i18n.js";

/**
 * Розкладка РЯДІВ, де ряд задано ззовні, а не нарізано по числу колонок.
 *
 * `rows`: `[[{ id, h }, …], …]` — кожен вкладений масив це один ряд у тому
 * порядку, у якому картки мають стояти. Кожна картка — `{ id, h }`, де `h` —
 * висота КАДРУ без голови. Повертає ПЛОСКИЙ `[{ id, x, y, h }]`, де `h` — уже
 * ПОВНА висота карточки (`head + кадр`), готова до `style.height`; не додавай
 * `head` ще раз. Плоский він навмисно: `worldBox` і виклики в `app.js` не мусять
 * знати, як ряд утворився.
 *
 * Чому ряди приходять ГОТОВИМИ, а не нарізаються тут по числу колонок: ряд
 * означає СТОРІНКУ з її станами, тобто його довжину задає модель, а не
 * геометрія. Нарізка по колонках робила ряд випадковим — рівно скарга «ряди в
 * Огляді нічого не означають».
 */
export function rowsLayout(rows, { cardW, gap, head }) {
  /* Непридатну висоту ловимо тут, а не малюємо негативний прямокутник: висота
     кадру приходить із манифеста, а манифест приїжджає з чужої машини. NaN у
     ньому — зламаний файл, про який треба сказати, а не тихо покласти на канвас
     порожнє місце. */
  for (const row of rows) {
    for (const card of row) {
      if (!Number.isFinite(card.h) || card.h < 0) {
        throw new Error(t('layoutCardHeight', card.id, card.h));
      }
    }
  }
  const placed = [];
  let y = 0;
  for (const row of rows) {
    /* Єдиний виклик (`buildRows`) порожнього ряду не дає: сторінка завжди кладе
       принаймні себе. Гілка тут заради тотальності чистої функції — без неї
       `Math.max()` без аргументів дає -Infinity, і всі наступні ряди їдуть
       у мінус нескінченність замість помітної помилки. */
    if (row.length === 0) continue;
    /* Висота РЯДУ і висота КАРТОЧКИ — різні речі, і це головне тут: ряд каже,
       де почнеться наступний, а карточка лишається своєї висоти. Роздай усім
       карточкам ряду висоту ряду — і коротка сторінка знову стане пустим
       простирадлом на висоту найдовшої статті. */
    const rowH = Math.max(...row.map((card) => head + card.h));
    row.forEach((card, col) => {
      placed.push({ id: card.id, x: col * (cardW + gap), y, h: head + card.h });
    });
    y += rowH + gap;
  }
  return placed;
}

/** Габарит світу, з якого рахується «вписати все». */
export function worldBox(placed, cardW) {
  if (placed.length === 0) return { w: 0, h: 0 };
  return {
    w: Math.max(...placed.map((p) => p.x + cardW)),
    h: Math.max(...placed.map((p) => p.y + p.h)),
  };
}
