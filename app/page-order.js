/**
 * Порядок сторінок у панелі: куди ляже сторінка, яку тягнуть або піднімають.
 * Чиста функція — ні DOM, ні fetch, — тому тестується в node
 * (`tests/page-order.test.mjs`).
 *
 * ⛔ Навіщо окремо (fb-09092026-d4c51b, 09.09.2026): «на одну вище» й «кинув
 * перед цим рядком» — два входи до ОДНІЄЇ арифметики позиції, і саме в ній
 * живе пастка зсуву: сторінка, яку тягнуть ВНИЗ, спершу виймається зі списку,
 * тож кожен рядок під нею зсувається на одну позицію вгору. Порахуй індекс
 * рядка-цілі «як бачиш» — і кинута вниз сторінка стає на одну нижче, ніж її
 * клали. Одна функція на обидва входи не дає цій пастці жити лише в одному.
 *
 * З 30.09.2026 перетягування рахує `planMove` (`tree-model.js`) і МІНЯЄ
 * вкладеність — видимо (рамка/лінія/підказка), див. `wirePageDrag`. Тут
 * лишились лише пункти меню «Підняти/Опустити» (`canMove`); `dropIndex` (одно-
 * рівнева арифметика кидка) прибрано 01.10.2026 — його не кликав ніхто, крім
 * власного тесту, а пастку зсуву тепер стереже `planMove` (tests/tree-model.test.mjs).
 */
import { findNode } from "./tree-model.js";

/** Сусіди сторінки: `{ parent, ids }` (parent `null` — верхній рівень) або `null`. */
export function siblingsOf(pages, id) {
  const r = findNode(pages, id);
  return r ? { parent: r.parent ? r.parent.id : null, ids: r.list.map((p) => p.id) } : null;
}

/** Чи є куди зрушити на `delta` (±1) — щоб пункт меню не обіцяв дії, якої немає. */
export function canMove(pages, id, delta) {
  const s = siblingsOf(pages, id);
  if (!s) return false;
  const to = s.ids.indexOf(id) + delta;
  return to >= 0 && to < s.ids.length;
}
