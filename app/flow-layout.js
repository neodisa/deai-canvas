/**
 * Чиста розкладка флоу: ранги → координати кадрів і точки ребер.
 * Ні DOM, ні fetch. Висоту кадру дає викликач (`heightOf`), бо вона приходить
 * із манифеста знімків, а модуль про знімки нічого не знає.
 */
import { t } from "./i18n.js";

/** Висота одного лейна під смугою. */
export const LANE_H = 60;

/**
 * @param {object} opts
 * @param {number} [opts.bandGap] відстань між смугами. ПАРАМЕТР, а не `gap * 2`
 *   намертво: смугу на канвасі малюють із полями навколо кадрів, тобто підкладка
 *   виступає за габарит, який рахує цей модуль, — і поки відстань була жорсткою,
 *   поля сусідніх смуг перекривались (виміряно на демо-графі блогу: накладка 40px,
 *   дві підкладки злипались у пляму). Про поля модуль не знає й не мусить: це DOM,
 *   а тут чиста розкладка. Замовчування — той самий подвійний зазор, щоб правка
 *   тихо не переставила смуги іншим викликачам.
 */
export function flowLayout(flows, heightOf,
                           { cardW, gap, head, laneH = LANE_H, bandGap = gap * 2 }) {
  const bands = [];
  let top = 0;
  let widest = 0;

  for (const flow of flows) {
    /* Пас 1: колонка, висота і бажаний ряд кожного вузла — з перевірками. Спершу
       всі числа, і лише потім геометрія: кривий кадр на канвасі гірший за
       помилку, яка називає вузол. */
    const wanted = [];
    for (const node of flow.nodes) {
      /* Непридатні числа ловимо тут, а не малюємо кривий кадр: висота приходить
         із манифеста знімків, і якщо там опинилось NaN чи мінус — це зламаний
         манифест, про який треба сказати. Та сама охорона й те саме формулювання,
         що в `rowsLayout` (`app/layout.js`), бо джерело в них спільне. */
      const body = heightOf(node.id);
      if (!Number.isFinite(body) || body < 0) {
        throw new Error(t('flowLayNodeHeight', node.id, body));
      }
      /* `pos` — рука дизайнера, і вона ПЕРЕБИВАЄ порахований ранг, а не
         додається до нього: авто-розкладка на складному графі ляже криво, і
         єдина відповідь на це — дати можливість поставити вузол самому. */
      const col = node.pos?.col ?? flow.ranks.get(node.id) ?? 0;
      /* Ранг — це НОМЕР колонки, тож лише ціле й невідʼємне. Дробовий поставив би
         кадр на пів-колонки, а до такого стрілці нема до чого чіплятись; відʼємний
         виніс би кадр за лівий край світу — `box` рахується від нуля, тож вміст
         поїхав би за канвас, і ніхто б не побачив, куди.

         Джерело числа в тексті РІЗНЕ, бо виправляти доводиться різні місця: ранг
         рахує граф із `edges`, а `pos` пишуть руками (драгом або прямо у файлі). */
      if (!Number.isInteger(col) || col < 0) {
        throw new Error(node.pos?.col === undefined
          ? t('flowLayRank', node.id, col)
          : t('flowLayPosCol', node.id, col));
      }
      const row = node.pos?.row;
      if (row !== undefined && (!Number.isInteger(row) || row < 0)) {
        throw new Error(t('flowLayPosRow', node.id, row));
      }
      wanted.push({ id: node.id, col, row, h: body + head });
    }

    /* Пас 2: порядок у колонці. `row` — це ПОЗИЦІЯ в колонці, а не піксель:
       інакше перезнята довша сторінка зсунула б усі руками поставлені вузли, і
       робота дизайнера пропала б без жодної помилки.

       Автовузли лягають у порядку опису, а руками поставлені ВСТАВЛЯЮТЬСЯ на свій
       індекс — не «сідають на порожнє місце з таким номером». Різниця несуща:
       найзвичайніший жест «потягнути вузол на верх колонки» дає `row: 0`, а
       нульовий ряд там уже займає автовузол за рангом — розкладка, що просто
       рахує «зверху нічого немає → y = 0», кладе два кадри в одну точку. Вставка
       ж заодно робить осмисленим `row: 9999` із руками правленого файла: вузол
       стає останнім, а не роздуває колонку на дев'ять тисяч порожніх рядів. */
    const order = new Map();         // колонка → впорядкований список вузлів
    const inCol = (col) => {
      if (!order.has(col)) order.set(col, []);
      return order.get(col);
    };
    for (const w of wanted) if (w.row === undefined) inCol(w.col).push(w);
    // Стабільне сортування за рядом: двоє з однаковим `row` лягають у порядку опису.
    for (const w of wanted.filter((x) => x.row !== undefined)
                          .sort((a, b) => a.row - b.row)) {
      inCol(w.col).splice(w.row, 0, w);
    }

    // Пас 3: y = сума висот тих, хто в колонці ВИЩЕ, із зазором між ними.
    const yOf = new Map();
    const colH = [];
    for (const list of order.values()) {
      let y = 0;
      for (const w of list) { yOf.set(w, y); y += w.h + gap; }
      colH.push(y - gap);             // без зайвого зазору в хвості
    }
    const placed = wanted.map((w) => ({ id: w.id, x: w.col * (cardW + gap),
                                        y: yOf.get(w), w: cardW, h: w.h, col: w.col }));
    const byId = new Map(placed.map((p) => [p.id, p]));
    // Висота смуги без лейнів: найдовша колонка.
    const contentH = Math.max(0, ...colH);

    const edges = [];
    let lane = 0;
    /* Скільки стояків уже стоїть у зазорі. Ключ — ЗАЗОР, а не колонка: зазор `g`
       лежить між колонками `g` і `g+1`, тож «лівий зазор колонки 1» і «правий
       зазор колонки 0» — це ОДНЕ І ТЕ САМЕ місце смуги. Лічильник, ключений
       колонкою (як стояло тут раніше), давав двом таким ребрам той самий `k`, а
       отже той самий `x`: два стояки злипались в одну лінію рівно в тому випадку,
       від якого лічильник і мусить стерегти. */
    const hooks = new Map();
    /* `x` наступного стояка в зазорі `g`, від ЛІВОГО краю зазору. `1 / (k + 2)` —
       щоб два стояки в одному зазорі не злиплись в одну лінію (та сама причина,
       що в окремих лейнів): 1/2, 1/3, 1/4 зазору — різні для кожного `k` і НІКОЛИ
       не виходять із зазору, скільки б ребер там не було. */
    const stalkIn = (g) => {
      const k = hooks.get(g) ?? 0;
      hooks.set(g, k + 1);
      return g * (cardW + gap) + cardW + gap / (k + 2);
    };
    /* Той бік кадру, що дивиться на стояк: лінія приходить збоку, і наконечник
       дивиться В кадр, а не вздовж нього. */
    const sideAt = (p, x) => (x < p.x ? p.x : p.x + p.w);
    for (const e of flow.edges) {
      const a = byId.get(e.from), b = byId.get(e.to);
      /* Передумова, а не мовчазне ковтання: ребра на вузли поза смугою `readFlow`
         відсіює в `problems` ще до розкладки, тож сюди вони не доходять і цей
         рядок недосяжний. Якщо колись задзвонить — лагодити треба виклик, який
         подав нефільтрований граф, а не глушити тут. */
      if (!a || !b) continue;
      if (b.col - a.col === 1) {
        /* Сусідні колонки: прямо через зазор, із середини A в середину B. Висоту
           беремо В КОЖНОГО СВОЮ, і лінія виходить похила — так і треба. Спільна
           висота джерела промахувалась повз ціль, щойно та стояла не в нульовому
           ряду або просто була іншої висоти: стрілка кінчалась у порожнечі. */
        edges.push({ ...e, points: [[a.x + a.w, a.y + a.h / 2], [b.x, b.y + b.h / 2]] });
      } else if (b.col === a.col) {
        /* ОДНА КОЛОНКА — окрема гілка, і без неї малюнок бреше ЗАВЖДИ, а не в
           крайньому випадку. `pos` перебиває ранг, тож найзвичайніший жест
           «поставити два звʼязані вузли один під одним» дає рівні колонки, а
           рівність падала в гілку лейна нижче: поперечка виходила нульової
           довжини, стояк повертався в ціль ТИМ САМИМ `x`, яким спускався, і
           креслив кадр навиліт (живий прогін: стояк x=2016 ішов y 2060 → 934
           крізь кадр джерела [1376..2656]×[1030..1964]).

           Ведемо стояк У ЗАЗОРІ поруч із колонкою: зазор — єдине місце смуги, де
           кадрів немає ніколи, тож перетнути там нічого не можна. Зазор ЛІВОРУЧ,
           якщо колонка не нульова, інакше правий: у нульової колонки лівого
           зазору немає, і стояк поїхав би за лівий край світу (`box` рахується
           від нуля), тобто за канвас — рівно те, чим погані відʼємні ранги вище.

           Вихід і вхід — у БІЧНІ краї кадрів, на висоті їхніх середин: лінія
           приходить збоку, і наконечник дивиться в кадр, а не вздовж нього.

           Лейн такому ребру не потрібен, тому `lane` не чіпаємо: смуга не
           виростає на порожнє місце під собою. */
        const stalk = stalkIn(a.col > 0 ? a.col - 1 : 0);
        edges.push({ ...e, points: [
          [sideAt(a, stalk), a.y + a.h / 2],
          [stalk, a.y + a.h / 2],
          [stalk, b.y + b.h / 2],
          [sideAt(b, stalk), b.y + b.h / 2],
        ] });
      } else {
        /* Через дві й більше (і будь-яке зворотне): вниз, лейном під смугою,
           вгору. Свій лейн кожному ребру — спільний лейн злипається в одну
           лінію, і читач не бачить, скільки насправді переходів.

           ШІСТЬ точок, а не чотири, і стояки — В ЗАЗОРАХ: спуск із-під ЦЕНТРУ
           кадру (як стояло тут раніше) креслив навиліт кожного, хто стоїть у тій
           самій колонці НИЖЧЕ джерела, — а це не крайній випадок, а два входи в
           графі, себто найзвичайніший граф із двома точками входу (`pos` для
           цього не потрібен зовсім). Живі числа: кадри a [0..100]×[0..60],
           z [0..100]×[80..140], ребро a→c [[50,60],[50,160],…] — відрізок
           60 → 160 на x=50 ішов крізь z наскрізь. Зазор — єдине місце смуги, де
           кадрів немає ніколи, тож перетнути там нічого не можна; та сама
           відповідь, що в гілці однієї колонки вище.

           Спуск ведемо зазором З ТОГО БОКУ, куди йде ребро, а підйом — з того,
           звідки воно приходить: у прямого це правий зазор джерела і лівий цілі,
           у зворотного навпаки. У зворотного ребра через ОДНУ колонку обидва
           зазори виявляються тим самим — і це не злипання: `stalkIn` дає двом
           стоякам різні `x`, просто поперечка лейна між ними коротка. */
        const back = b.col < a.col;
        const xa = stalkIn(back ? a.col - 1 : a.col);
        const xb = stalkIn(back ? b.col : b.col - 1);
        const laneY = contentH + gap + lane * laneH;
        lane += 1;
        edges.push({ ...e, points: [
          [sideAt(a, xa), a.y + a.h / 2],
          [xa, a.y + a.h / 2],
          [xa, laneY],
          [xb, laneY],
          /* Вгору зазором до висоти середини цілі й ЗБОКУ в неї. Вести стояк до
             центру кадру (`b.x + b.w / 2`) означало б знову лізти в колонку — а
             там кадри, і нижчий сусід цілі був би прокреслений навиліт. */
          [xb, b.y + b.h / 2],
          [sideAt(b, xb), b.y + b.h / 2],
        ] });
      }
    }

    /* Під останнім лейном лишається ще один `laneH` — це не зайвина, а місце
       під підпис ребра, який стоїть на лінії. */
    const h = contentH + (lane ? gap + lane * laneH : 0);
    const w = Math.max(0, ...placed.map((p) => p.x + p.w));
    widest = Math.max(widest, w);
    bands.push({ id: flow.id, title: flow.title, y: top, h, contentH, placed, edges });
    top += h + bandGap;              // смуги стопкою, з відстанню від викликача
  }

  const last = bands[bands.length - 1];
  return { bands, box: { w: widest, h: last ? last.y + last.h : 0 } };
}
