/**
 * Склад ряду сіткового виду. Чиста функція: ні DOM, ні fetch — тому
 * тестується в node (`tests/rows-model.test.mjs`), як `flow-model.js`.
 *
 * Ряд = ОДНА сторінка й усе, що під нею. До правки 31.08.2026 ряд був нарізкою
 * плоского переліку по три (число колонок стояло константою в геометрії й
 * прибране тією ж правкою), тобто не означав нічого: перенос на новий ряд був
 * випадковим, а стани сторінки в сітці не показувались узагалі — вони жили лише
 * у флоу-виді.
 *
 * ⛔ Опора на СТРУКТУРУ, а не на імена. У живих даних стан буває трьома
 * способами: дочірньою сторінкою («Стан: порожньо» в `boss-interface/it2`),
 * дочірньою сторінкою, яка станом НЕ є («Ваші компанії» в `it1`), і вузлом
 * `flow.json`. Відрізнити перше від другого можна тільки за префіксом в імені —
 * і робити таке соглашення несучим не можна: перейменування мовчки викидало б
 * стан із ряду. Тому ряд — це «сторінка й усе вкладене», а не «сторінка та її
 * стани за назвою».
 *
 * З 30.09.2026 тип вузла явний (`kind`, `app/tree-model.js`); для файлів без нього
 * діє той самий вивід, що панель: дитина сторінки = стан.
 *
 * Дитина легасі-теки (`isGroup`) ВСЕРЕДИНІ сторінки тепер підсторінка зі своїм
 * рядом, а не стан: так її виводить `pm.flatten` (батьківський тип — folder).
 */

import { kindOf } from "./tree-model.js";

/**
 * `pages` — дерево з `/api/iteration-pages`; `nodes` — плоский перелік вузлів
 * усіх смуг (`readFlow(...).flows.flatMap(f => f.nodes)`).
 *
 * Повертає масив рядів. Ряд — це масив карток `{ key, page, state, label,
 * published }` ПЛЮС властивість `title` (імʼя верхньорівневої сторінки) на
 * самому масиві: підпис належить ряду, а не картці, і окрема обгортка тут була б
 * зайвим шаром заради одного поля.
 *
 * ⚠️ `title` лежить НЕ в масиві, а НА ньому — власною не-індексною властивістю,
 * і будь-яка нова копія масиву її не переносить: `.filter()`, `.slice()`,
 * `.map()`, спред, `.concat()`, `JSON.stringify` (перевірено, node v22.14.0).
 * Тобто одне безневинне перетворення між `buildRows` і малюванням — і ряди
 * лишаються на вигляд цілими, а підписи зникають безшумно. Прецедент у цьому ж
 * репо: `nodeList` (`bin/shoot.mjs:49`) відкинув рівно такий дизайн для
 * `problems` і повернув `{ nodes, problems }`. Тут форма лишається, бо `app.js`
 * читає `row.title` ДО будь-якого перетворення — саме тому це місце й треба
 * знати, перш ніж таке перетворення дописати.
 */
export function buildRows(pages, nodes) {
  /* Стани групуємо по сторінці ОДИН раз: інакше на кожну сторінку йшов би повний
     прохід по вузлах, а вузлів у великому графі більше, ніж сторінок.

     Порядок станів усередині сторінки = порядок вузлів у `flow.json` (між
     смугами — порядок смуг, бо викликач подає `flows.flatMap(f => f.nodes)`).
     Це НАВМИСНО, а не «як вийшло»: `flow.json` пишуть руками, і послідовність
     станів у ньому — авторська розповідь («порожньо → завантаження → готово»).
     Сортування тут (за ключем чи підписом) перемішало б її на догоду алфавіту.
     Зворотний бік чесний і очікуваний: переставили вузли у файлі — переставились
     картки в ряду. */
  const statesOf = new Map();
  const seen = new Set();
  for (const n of nodes) {
    /* Вузол, який означає САМУ сторінку, а не її стан: сторінка вже прийшла з
       дерева, тож другий раз її класти не можна.

       Питання ставимо про КЛЮЧ КАДРУ, а не про поле `state`, і перевірка тут
       свідомо ОДНА. Бути «без стану» можна двома способами: поля немає зовсім
       (`state: null`) або воно Є, але порожнє за змістом (`"state": {}`,
       `{"q": ""}` — `checkState` таке пропускає, а `normalizeState` порожні
       значення викидає). Обидва шляхи сходяться в одному: `shotKey` віддає
       ГОЛИЙ id сторінки (перевірено для null/undefined/{}/{q:""}/{q:null}).
       Тому `!n.state` як окрема половина умови була б МЕРТВОЮ — вона не може
       спрацювати там, де не спрацював ключ, і жодна мутація не зробила б її
       червоною. Перевірка форми поля ловила б лише перший спосіб, а `flow.json`
       пишуть руками, тож `"state": {}` цілком досяжний.

       `seen` тут не рятує: він дедуплікує вузли МІЖ СОБОЮ, а колізія — між
       вузлом і деревом. `buildRows` — перше місце, де ці два джерела
       зливаються, тому питання мусить ставити саме воно. */
    if (n.key === n.page) continue;
    if (seen.has(n.key)) continue;   // той самий стан у двох смугах — один кадр
    seen.add(n.key);
    if (!statesOf.has(n.page)) statesOf.set(n.page, []);
    statesOf.get(n.page).push({ key: n.key, page: n.page, state: n.state, label: n.label });
  }

  const rows = [];

  /**
   * Ряд однієї сторінки: вона сама, її flow-стани, стани-вузли дерева на БУДЬ-якій
   * глибині КРІЗЬ теки (тека сторінки = її віджет), але НЕ крізь дочірні
   * сторінки: підсторінка — окремий екран і дістає ВЛАСНИЙ ряд одразу після
   * батьківського (рішення власника 30.09.2026), із заголовком-шляхом.
   *
   * `up` — чи видимі в превʼю всі предки: приховування діє на піддерево
   * (рішення власника 30.09.2026), тож крапка стану = видимість його ланцюжка.
   */
  const rowFor = (pg, title, up) => {
    const row = [];
    const subpages = [];
    const put = (node, label, published) => {
      row.push({ key: node.id, page: node.id, state: null, label, published });
      for (const st of statesOf.get(node.id) ?? []) row.push({ ...st, published });
    };
    const own = up && pg.published !== false;
    put(pg, pg.name, own);
    const collect = (list, parentKind, trail, vis) => {
      for (const ch of list ?? []) {
        const kind = kindOf(ch, parentKind);
        const pub = vis && ch.published !== false;
        if (kind === "page") { subpages.push({ node: ch, up: vis }); continue; }
        if (kind === "folder") { collect(ch.children, "folder", [...trail, ch.name], pub); continue; }
        put(ch, [...trail, ch.name].join(" · "), pub);
      }
    };
    collect(pg.children, "page", [], own);
    row.title = title;
    rows.push(row);
    for (const s of subpages) rowFor(s.node, `${title} › ${s.node.name}`, s.up);
  };

  /* Тека — НЕ ряд: власного кадру в неї немає. Спускаємось і шукаємо сторінки
     на будь-якій глибині; стан у корені чи в кореневій теці — невалідне дерево
     (`validate`), тут його просто пропускаємо. */
  const visit = (list, parentKind, up) => {
    for (const n of list ?? []) {
      const kind = kindOf(n, parentKind);
      if (kind === "folder") { visit(n.children, "folder", up && n.published !== false); continue; }
      if (kind === "page") rowFor(n, n.name, up);
    }
  };
  visit(pages, null, true);
  return rows;
}
