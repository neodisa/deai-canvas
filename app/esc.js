/**
 * Текст → безпечний для `innerHTML`.
 *
 * Чотири символи, і рівно ці: `&` (інакше екранування зʼїдало б саме себе),
 * `<`/`>` (розмітка) і `"` (вихід з атрибута, у який цей рядок здебільшого й
 * підставляють). Апостроф НЕ екранується — атрибути в цьому репозиторії
 * пишуться подвійними лапками; кому потрібен ширший набір, той будує його
 * ПОВЕРХ цієї функції, а не поруч із нею (див. `esc` у
 * `app/vendor/inspector.js`).
 *
 * `?? ''` — бо `null`/`undefined` мусять дати порожньо, а не рядок «null»:
 * підпис без назви краще показати порожнім, ніж словом «undefined».
 */
export const esc = (s) => String(s ?? "").replace(/[&<>"]/g,
  (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
