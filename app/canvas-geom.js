/**
 * Поля смуги сценарію — те «пікселів по 100 або більше», яке просив дизайнер:
 * підкладка смуги мусить читатись як навмисна рамка навколо кадрів, а не як
 * обведення по їхньому габариту.
 *
 * Бокове поле дорівнює зазору: інакше кадр стоїть до краю смуги ближче, ніж до
 * сусіда, і смуга виглядає тіснішою за свій вміст.
 *
 * Верхнє БІЛЬШЕ за нижнє навмисно: у ньому живе підпис смуги (`.cv-band-title`),
 * і поле мусить його вмістити на людському зумі. Порожня рамка згори, під якою
 * стоїть назва сценарію, — це те, як виглядають секції в макетних редакторах;
 * симетричні поля з підписом, який лізе на кадри, виглядали б помилкою.
 *
 * Чому саме 200/160, а не «чим більше, тим краще»: поля роздувають СВІТ, а
 * «вписати все» має ПІДЛОГУ масштабу (`MIN_SCALE` у `camera.js`), нижче якої не
 * зменшує. На демо-задачі блогу (сторінка статті — 8000px) світ стоїть просто
 * впритул до неї, і це виміряно: на полях 240/200 світ 18439px, тобто на масштабі
 * 0.05 йому треба 922px полотна, а вікно 1600×950 дає 904 — зрізало 20px разом із
 * половиною підпису першої смуги. На 200/160 світ 18079px, тобто рівно 904px:
 * влазить, але запас нульовий, а на нижчому вікні зріже знову (до правки треба було
 * 853px, тобто впритул було вже тоді).
 *
 * Тобто поля тут не «на смак»: кожні 100px поля — це 5px екрана на bird-view демо.
 * Структурно це не поля лікують, а окрема підлога для «вписати все» (як уже є
 * окрема СТЕЛЯ, `FIT_MAX_SCALE`) — але то рішення камери, і його ніхто не просив.
 */
export const BAND_PAD_X = 200;
export const BAND_PAD_TOP = 200;
export const BAND_PAD_BOTTOM = 160;

/**
 * Звідки починається вміст флоу-світу. Рівно поля першої смуги: `#world` не має
 * відʼємних координат — «вписати все» рахує габарит від нуля, тож усе, що поїхало
 * ліворуч чи вище нуля, камера зрізає (це стереже жива перевірка I). Тому не
 * смуга росте назовні, а вміст зсувається всередину.
 */
export const FLOW_LEFT = BAND_PAD_X;
export const FLOW_TOP = BAND_PAD_TOP;

/**
 * Скільки світових пікселів лишити над рядом під його підпис.
 *
 * Підпис іде ЗВЕРХИ, а не збоку, і це не смак. `#world` не має відʼємних
 * координат (див. `FLOW_LEFT` вище), тож підпис збоку мусив би жити у
 * ФІКСОВАНОМУ лівому полі — а кегль у нього контр-масштабований і на bird-view
 * росте у світі. У поле шириною навіть 1200px влазило б 4-5 символів у рядок,
 * тобто варіант ламався саме там, заради чого обирався. Зверху підпис іде
 * вправо у відкритий простір (`nowrap`), як у смуги.
 *
 * Чому саме 160, а не «на око». Число затиснуте з двох боків, і обидва виміряні
 * на задачі з 8 сторінок (її власний fit — масштаб 0.0816):
 *
 *   • ЗВЕРХУ його тримає `GAP` (200). Смуга під підпис вирізається із зазору між
 *     рядами — єдиного місця сітки, де кадрів немає ніколи. Узяти весь зазор не
 *     можна: підпис торкався б низу ряду ВИЩЕ і читався б як підпис того ряду.
 *     40px, що лишаються, — просвіт, який видно (на bird-view це 3px екрана).
 *   • ЗНИЗУ його тримає стеля кегля в `.cv-row-title`: коробка підпису мусить
 *     улазити в цю смугу цілком, інакше підпис лізе на ВЛАСНИЙ кадр — при стелі
 *     260px і відступі 120px він накривав 186 світових px кадру, тобто всю голову
 *     й ще 152px знімка, голим текстом по скріншоту. Коробка = кегль × 1.2
 *     (`line-height` там заданий явно саме щоб це рівняння було правдою на
 *     будь-якій платформі), тож 160 дозволяє стелю 132px — і це найбільша стеля,
 *     тобто найчитніший підпис із тих, що на кадр не лізуть: 10.8px екрана на
 *     bird-view проти 8.2px, які дав би відступ 120.
 *
 * Тобто відступ і стеля — одне рішення у двох файлах: змінюючи одне, проміряй
 * друге (стереже жива перевірка AC: «коробка підпису влазить у смугу над рядом»).
 */
export const ROW_TITLE_TOP = 160;
