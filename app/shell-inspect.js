/**
 * Розмітка правої панелі інспектора (Task 5 Плану B) — стан на вході, рядок
 * HTML на виході, і нічого крім цього: та сама ідіома, що в `shell-bar.js`
 * (Task 2) і `shell-panel.js` (Task 4) — жодного слухача, жодного звернення
 * до DOM. Проводку (`data-act` → дія) робить `app.js` однією делегацією на
 * контейнер `#insp-panel`, за тим самим патерном, що й у панелі шарів
 * (`wirePanelEvents`), і кличе ТУ САМУ мапу дій, що й смуга (`BAR_ACTIONS`,
 * `app.js`) — не другу: `[data-act="inspector"]` тут (кнопка закриття) і в
 * смузі (кнопка відкриття) мусять лишатись рівно одним рішенням «увімкнено/
 * вимкнено», а не двома реалізаціями, що можуть розійтись.
 *
 * Джерело вигляду — затверджений прототип `docs/proto/shell.html`, функції
 * `renderRight`/`inspPanel`: заголовок (іконка + назва + закриття), сегмент
 * вкладок, підпис із клавішами внизу. Розкладку самого звіту й підвал задає
 * ДРУГИЙ затверджений макет — `docs/proto/tuner-panel.html`, варіант А
 * (T-39).
 *
 * ⛔ ВКЛАДОК ДВІ: «Стилі» і «Лінійка». Третя, «Тюнер» (Task 15), прожила до
 * T-39 і зникла — не тому, що її вміст став непотрібним, а тому, що він
 * стосується РІВНО тієї роботи, яку роблять у «Стилях»: список накрученого,
 * записка й дві дії переїхали в ПІДВАЛ цієї ж вкладки. Крутити в одному
 * місці, а надсилати в іншому — зайвий перехід усередині однієї роботи.
 *
 * Звіт про елемент малюється ТУТ, але НЕ рахується тут. Рахує його
 * `describeAll()` (`app/vendor/inspector-dom.js`) усередині iframe макета —
 * єдиний код, що бачить живий DOM, — і віддає готовий серіалізовний payload
 * нагору (`CanvasInspector.report()`, міст `app.js:inspectorApi`). Панель
 * отримує його в `state.report` і передає чистому рендереру
 * `vendor/insp-report.js`. Шлях підрахунку каскаду лишається ОДИН.
 *
 * До 17.09.2026 тут стояв протилежний висновок — що звіт має лишитись в
 * оверлеї, бо друге читання DOM завело б другий шлях. Заперечення було
 * правильне і лишається чинним: його знято не відмовою від нього, а тим, що
 * панель не читає DOM узагалі.
 *
 * Демо-числа прототипу (падинги «12 14 --sp-3», кольори «#1A1C1F --ink»,
 * відстані «24 px») сюди не поїхали й тепер уже не поїдуть: вигадані
 * ілюстративні значення статичного макета заступив справжній payload, а коли
 * його немає (нічого не запінено) — підказка, що саме показує оверлей у
 * поточному режимі. ВИДИМИЙ перемикач режиму (замість самих лише клавіш)
 * лишається там, де й був.
 *
 * `inspectHTML(state)`. `state`:
 *   shellMode: 'layout' | 'overview' — той самий термін, що в `barState().mode`
 *     (`app.js`). Інспектор — оверлей у iframe МАКЕТА: у «Огляді» кадри
 *     полотна — це знімки (`<img>`), живого DOM там немає, і оверлею нема на
 *     чому малювати рамки. Тому панель, як і кнопка інспектора в смузі
 *     (`shell-bar.js`, `TIERS.view`), існує ЛИШЕ в «Макеті».
 *   on: boolean — `CanvasInspector.on` (інспектор увімкнений)
 *   mode: 'cascade' | 'ruler' — `CanvasInspector.mode`, і він же АКТИВНА
 *     ВКЛАДКА. Окремого поля `tab` більше немає (T-39): доки вкладок було
 *     три, а режимів два, панель мусила тримати власний вибір, і `app.js`
 *     тримав під це цілий механізм поколінь документа, щоб відрізнити
 *     «натиснули M» від «рамка перезавантажилась». Вкладки й режими знову
 *     одне й те саме — і друге джерело правди про показане зникло.
 *   tune: пакет `packageJSON(tuneState, page)` (`app/tuner-model.js`) або
 *     null — що накручено на ЦІЙ сторінці, записка Клоду і `status`
 *     («чернетка»/«готово»). Той самий принцип, що з `report`/`measure`:
 *     панель його не рахує, лише малює.
 *   tuneOther: number — скільки правок лежить на ІНШИХ сторінках. Окремим
 *     числом, бо `tune` за визначенням не може їх нести: сторінка — межа
 *     видимості правок, і мовчазне «їх немає» було б неправдою про пакет.
 *   tuneMissing: [{selector, prop}] — правки, які на ЦЬОМУ документі макета не
 *     лежать (`tuneMissing`, `app.js`). ⛔ Окремим полем, а не всередині
 *     пакета, і це не стиль: пакет — НАМІР дизайнера, той самий, що їде на
 *     диск і Клоду; «лягло чи ні» — факт про рамку, яка зараз на екрані, і в
 *     файл йому не можна. Малюється позначкою в рядку списку змін: правку ми
 *     не викидаємо (вона описує зроблене), але й не смієм показувати її так
 *     само, як ту, що на макеті справді стоїть.
 *   report: payload `CanvasInspector.report()` або null/undefined — готовий
 *     звіт про ЗАПІНЕНИЙ елемент (крихти, секції, застереження). Тут його не
 *     рахують і не доповнюють: панель лише передає його в `reportHTML`. Немає
 *     піна — немає звіту, і тоді в тілі лишається підказка. У режимі лінійки
 *     звіту теж не місце, навіть коли payload приїхав: лінійка міряє відстані
 *     між якорем і сусідом і малює їх на самому макеті, а каскад запіненого
 *     елемента до неї стосунку не має (`_draw`, гілка 'ruler').
 *   measure: payload `CanvasInspector.measure()` або null/undefined — числа
 *     ЛІНІЙКИ (Task 7). Симетрично до `report`: рахує їх оверлей, панель лише
 *     передає в `measureHTML`. Це РІВНО ті числа, що зараз на напрямних —
 *     оверлей віддає той самий підсумок, який щойно намалював, а не рахує
 *     геометрію вдруге. Самі НАПРЯМНІ лишаються на макеті: лінію можна
 *     провести тільки поверх того, що міряють.
 *
 * Повертає `''`, коли панелі не місце (не «Макет», або інспектор вимкнений) —
 * той самий патерн, що `renderRight` прототипу (`if (S.right !== 'inspector'
 * || S.mode !== 'layout') return '';`). Порожній рядок — не порожня панель:
 * `app.js` (`paintInsp`) читає його ж, щоб вирішити, чи прибирати контейнер
 * із розкладки (`hidden`, клас `with-insp`) — одне рішення, а не два.
 */

