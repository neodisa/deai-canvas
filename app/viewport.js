/* Ширина робочого вида макета: пресети пристроїв і розбір довільного числа.
   Чистий модуль — ні DOM, ні fetch, ні localStorage (сховище читає той, хто його
   має; сюди приходить уже рядок). Тестується юнітами, як camera.js і layout.js.

   ЄДИНА величина стану — ширина в пікселях або `null` (десктоп, вільна ширина
   вікна). Другого прапорця «режим» немає зумисно: підсвітка сегмента виводиться
   з ширини (`activePreset`), тому «вибрав планшет» і «набрав 768 руками» — це
   один і той самий стан, а не два, які колись розійдуться. */
import { t } from "./i18n.js";

/** Найвужче, що має сенс показувати: вужче за 240 не існує живих екранів. */
export const MIN_W = 240;
/** Найширше: 4K. Вище — не перегляд, а промах по клавіатурі. */
export const MAX_W = 3840;

/* Реальні пристрої, а не брейкпоінти наших макетів (рішення дизайнера
   01.09.2026). Сенс саме в розбіжності: у design-work живе `max-width:760px`, і
   справжній iPad (768) його не вмикає. Перемикач мусить показувати цю дірку, а
   не ховати її зручним числом. */
export const PRESETS = [
  { id: 'desktop', w: null,
    get label() { return t('vpDesktop'); },
    get hint() { return t('vpDesktopHint'); } },
  { id: 'tablet', w: 768,
    get label() { return t('vpTablet'); },
    get hint() { return t('vpTabletHint'); } },
  /* 375, а не 390 (рішення власника 29.09.2026): це токен ДС
     `--screen-size-375-mobile` і ширина, на якій Ольга робить мобільні макети
     United. На 390 сторінка 375 отримувала поля по 7.5px, а піни — підпис
     «мобільна · 390» до дизайну під 375. Кадри старих задач `@390` під новий
     ключ `@375` не підходять — «Огляд» знімає їх заново. */
  { id: 'mobile', w: 375,
    get label() { return t('vpMobile'); },
    get hint() { return t('vpMobileHint'); } },
];

/** Пресет, який відповідає ширині, або `null`, якщо ширина своя. */
export function activePreset(w) {
  const hit = PRESETS.find((p) => p.w === w);
  return hit ? hit.id : null;
}

/* Число з поля вводу. Хвіст `px` приймаємо: саме в такому вигляді ширину
   копіюють із девтулзів і з медіа-запиту. */
const NUM_RE = /^-?\d+(?:\.\d+)?$/;

/**
 * Розбір довільної ширини.
 * @returns {{ok:true,w:number,clamped:boolean}|{ok:false,reason:'empty'|'nan'}}
 */
export function parseWidth(raw) {
  if (raw === null || raw === undefined) return { ok: false, reason: 'empty' };
  const s = String(raw).trim().replace(/\s*px$/i, '').trim();
  if (!s) return { ok: false, reason: 'empty' };
  if (!NUM_RE.test(s)) return { ok: false, reason: 'nan' };
  const n = Math.round(Number(s));
  /* Затискаємо, а не відкидаємо: «20» — не описка, а намір «якнайвужче», і
     відмова лишила б у полі число, якого немає на екрані. `clamped` існує, щоб
     інтерфейс сказав уголос, що число підмінили. */
  if (n < MIN_W) return { ok: true, w: MIN_W, clamped: true };
  if (n > MAX_W) return { ok: true, w: MAX_W, clamped: true };
  return { ok: true, w: n, clamped: false };
}

/** Що покласти в сховище. Десктоп — словом, не порожнім рядком. */
export function storeValue(w) {
  return w === null ? 'desktop' : String(w);
}

/**
 * Що прочитати зі сховища. Усе незрозуміле — десктоп: інструмент не має падати
 * через рядок, який хтось правив руками. Числа проходять ТОЙ САМИЙ затиск, що й
 * ввід, інакше в стилі опинилось би 99999px після зміни діапазону.
 */
export function readStored(raw) {
  if (raw === null || raw === undefined || raw === 'desktop') return null;
  const r = parseWidth(raw);
  return r.ok ? r.w : null;
}

/**
 * Ширина, якою знімається «Огляд» за замовчуванням. Це та сама ширина, якою
 * знімали до появи вьюпортів на полотні, і саме тому вона типова: ключі наявних
 * кадрів не змінюються, міграції немає.
 * ⚠️ Мусить дорівнювати `CARD_W` у `app/canvas-geom.js` — звірку тримає тест.
 */
export const CANVAS_W = 1280;

/**
 * Пресети ПОЛОТНА. Відрізняються від `PRESETS` одним: «Десктоп» тут ЧИСЛО, бо на
 * полотні немає вікна, ширину якого можна взяти. Поля довільної ширини в
 * «Огляді» немає свідомо — там кожна ширина це окремий набір знімків на диску.
 */
export const CANVAS_PRESETS = PRESETS.map((p) => ({
  id: p.id,
  w: p.w ?? CANVAS_W,
  /* `label`/`hint` — ГЕТТЕРИ, а не спред `...p`. Спред копіює РЕЗУЛЬТАТ
     виклику геттера в момент, коли рахується сам `.map()` — тобто один раз при
     імпорті, ДО того як хтось перемкне мову. Це та сама пастка, що й у
     `PRESETS` вище, тільки на крок далі: масив, зібраний з масиву геттерів,
     сам мусить лишитись масивом геттерів, інакше застигання ховається за
     спредом, і мутація, яка ловить пастку в `PRESETS`, цю не бачить.
     Підказка для «Десктоп» — своя, і не для краси: успадкована від `PRESETS`
     казала б у «Огляді» «вільна ширина вікна», хоч вільної ширини вікна там
     немає за визначенням — кадр знімається у фіксованих 1280. Тултіп, який
     описує не той механізм, гірший за відсутній: він відправляє шукати
     причину не туди. */
  get label() { return p.label; },
  get hint() { return p.w === null ? t('vpCanvasDesktopHint', CANVAS_W) : p.hint; },
}));

/** Ключ кадру з шириною. Типова ширина суфікса НЕ додає — див. `CANVAS_W`. */
export function frameKey(key, w) {
  return w === CANVAS_W ? key : `${key}@${w}`;
}

const FRAME_KEY_RE = /^(.*)@([1-9]\d{1,3})$/;

/**
 * Ключ кадру → `{key, w}`. Усе, що не схоже на ширину, лишається частиною
 * ключа: манифест приїжджає з чужої машини, і сміття не сміє прикидатись
 * шириною — інакше кадр поїхав би не в ту колонку полотна.
 */
export function splitFrameKey(id) {
  const m = FRAME_KEY_RE.exec(String(id));
  return m ? { key: m[1], w: Number(m[2]) } : { key: String(id), w: CANVAS_W };
}
