/* Охоронець від відкату i18n. Ловить рядки з кирилицею, які повернулись у код
   замість словника.
 *
 * Межа перевірки записана свідомо: дивимось у СТРОКОВІ ЛІТЕРАЛИ, а не в будь-яку
 * кирилицю у файлі. Коментарі в цьому репозиторії — головна документація, і вони
 * українською; у них кирилиця стоїть у «ялинках», а не в лапках, тож
 * literal-скан їх не чіпає. Перед скануванням коментарі все одно вирізаються —
 * інакше приклад коду всередині коментаря читався б як живий код.
 *
 * Шаблонні літерали (`…`) РАНІШЕ не скануались — «регекспом їх надійно не
 * розібрати». Ця межа виявилась дірою, і не теоретичною: `Іт.${n}` у крошці
 * й у переліку ітерацій — найпомітніший службовий рядок усієї смуги — стояв
 * шаблонним літералом просто в `app.js` і в English-режимі лишався
 * кирилицею, поки в словнику лежав готовий, але нікем не покликаний
 * `glIterationTag: (n) => `It.${n}``. Разом із ним крізь ту саму діру
 * пролізли два тости зупинки зʼємки. Тому нижче стоїть ДРУГИЙ сканер —
 * власний посимвольний (не регексп): він знімає текст шаблону, пропускаючи
 * вкладені `${…}` разом із їхніми лапками. */
const CYRILLIC = /[а-яіїєґА-ЯІЇЄҐ]/;

/** Вирізає коментарі, зберігаючи довжину файла — щоб позиції не з'їхали. */
function blankComments(src) {
  const buf = [...src];
  for (const m of src.matchAll(/\/\*[\s\S]*?\*\/|(?<!:)\/\/[^\n]*/g)) {
    for (let k = m.index; k < m.index + m[0].length; k += 1) {
      if (buf[k] !== "\n") buf[k] = " ";
    }
  }
  return buf.join("");
}

/** Межі тіла функції за збалансованими дужками — не за регекспом по рядках. */
function bodySpan(src, headerRe) {
  const m = headerRe.exec(src);
  if (!m) return null;
  const open = src.indexOf("{", m.index);
  let depth = 0;
  for (let j = open; j < src.length; j += 1) {
    if (src[j] === "{") depth += 1;
    else if (src[j] === "}") {
      depth -= 1;
      if (depth === 0) return [m.index, j + 1];
    }
  }
  return null;
}

/* Символи, після яких `/` починає РЕГЕКСП, а не ділення — та сама
   евристика «за попереднім значущим символом», що в будь-якому лексері JS.
   Потрібна вона рівно для `/[&<>"]/g` (той самий `esc` у пʼятьох модулях
   оболонки): без розрізнення лапка ВСЕРЕДИНІ регекспа зсувала б парування
   решти файла — знову «літерал, якого сканер не бачить». Виміряно: цією
   евристикою на 15 модулях розпізнано 13 регекспів і НІ ОДНОГО ділення
   хибно (ділення в цьому коді завжди стоїть після імені, числа або `)`). */
const REGEX_AFTER = /(?:[(,=:;[!&|?+\-*%~^<>]|\b(?:return|typeof|case|in|of|new|void|delete|instanceof|yield|await|do|else))$/;

/**
 * Строкові літерали файла — власним лексером, не плоским регекспом:
 * `[{index, text}]`.
 *
 * ⚠️ ЧОМУ НЕ РЕГЕКСП. Плоский `"…"` по сирцю не бачить літерала, вкладеного
 * в `${…}` шаблону, і це не теорія: другий замір передрелізного аудиту —
 * `app/shell-panel.js:60`, `title="${esc(t("pageActions"))}"` →
 * `title="${esc("Дії зі сторінкою")}"` — проходив НАВІТЬ після того, як межу
 * сканера перевернули з дозвільної на заборонну. Причина в паруванні лапок
 * навхрест: регексп бачить `"${esc("` одним літералом, `")}"` другим, а сам
 * напис — між ними, тобто ні в одному з двох. А підписи цієї оболонки саме
 * такі за формою: атрибут усередині шаблону розмітки.
 *
 * Стан-машина розрізняє три речі, які плоскому регекспу не даються:
 *   · `'…'`/`"…"` на ЛЮБІЙ глибині, зокрема всередині `${…}`;
 *   · шаблон `` `…` ``: його ТЕКСТ — справа сканера шаблонів нижче (він і
 *     лишається окремим тестом), а `${…}` — це знову код, отже знову місце
 *     для літералів;
 *   · регекспні літерали (див. `REGEX_AFTER` вище).
 *
 * Межа записана: лексер не розбирає JSX (його тут немає) і покладається на
 * те, що коментарі вже забілені (`blankComments` кличеться перед ним) —
 * інакше `//` і `/* *­/` читались би як регекспи.
 */
function stringLiterals(src) {
  const out = [];
  /* Стек контекстів: 'code' | 'tpl'. Вхід у `${…}` кладе 'code' ПОВЕРХ
     'tpl', і `brace` рахує глибину `{}` у цьому 'code' — щоб об'єктний
     літерал усередині підстановки (`${({a:1})[k]}`) не закрив підстановку
     раніше часу. */
  const stack = ["code"];
  const brace = [0];
  for (let i = 0; i < src.length; i += 1) {
    const ctx = stack[stack.length - 1];
    const c = src[i];
    if (ctx === "tpl") {
      if (c === "\\") { i += 1; continue; }
      if (c === "`") { stack.pop(); continue; }
      if (c === "$" && src[i + 1] === "{") { stack.push("code"); brace.push(0); i += 1; }
      continue;
    }
    if (c === "'" || c === '"') {
      const start = i;
      i += 1;
      // `\n` теж закриває: незакритий літерал не сміє зʼїсти пів файла.
      while (i < src.length && src[i] !== c && src[i] !== "\n") {
        if (src[i] === "\\") i += 1;
        i += 1;
      }
      out.push({ index: start, text: src.slice(start, i + 1) });
      continue;
    }
    if (c === "`") { stack.push("tpl"); continue; }
    if (c === "{") { brace[brace.length - 1] += 1; continue; }
    if (c === "}") {
      if (brace[brace.length - 1] === 0 && stack.length > 1) { stack.pop(); brace.pop(); }
      else brace[brace.length - 1] -= 1;
      continue;
    }
    if (c === "/" && REGEX_AFTER.test(src.slice(0, i).replace(/\s+$/, ""))) {
      i += 1;
      let inClass = false;
      while (i < src.length && src[i] !== "\n") {
        if (src[i] === "\\") { i += 2; continue; }
        if (src[i] === "[") inClass = true;
        else if (src[i] === "]") inClass = false;
        else if (src[i] === "/" && !inClass) break;
        i += 1;
      }
    }
  }
  return out;
}

/* ── межа сканера літералів ЗАБОРОННА, а не дозвільна ────────────────────
 *
 * Раніше тут стояв СПИСОК ДОЗВОЛУ: десять «чистих модулів» плюс окремий тест
 * на `app.js`. Передрелізний аудит показав, чим такий список кінчається.
 * План B приніс чотири НОВІ модулі, які тепер малюють 100% смуги, панелі,
 * інспектора й палітри — `shell-bar.js`, `shell-panel.js`, `shell-inspect.js`,
 * `shell-palette.js`, — і жоден із них у список ніхто не дописав. Заміри
 * (обидва на повному `node --test tests/*.test.mjs`, 343 pass / 0 fail):
 *   · `app/shell-bar.js`   `esc(t("tasks"))`       → `esc("Задачі")`
 *   · `app/shell-panel.js` `esc(t("pageActions"))` → `esc("Дії зі сторінкою")`
 * Тобто найпомітніші підписи смуги й панелі можна було прибити гвіздком до
 * української — і охоронець i18n цього не бачив, бо дивився не туди, куди
 * переїхав текст.
 *
 * Тому межа перевернута: скануються УСІ `app/*.js`, крім `i18n.js`, а винятки
 * виписані явно й з причиною — той самий прийом, що вже стоїть для `EXEMPT`
 * у сканері шаблонів нижче. Полагодити це дописуванням чотирьох рядків у
 * список означало б чекати на п'ятий модуль: список, який треба доповнювати
 * руками, забудуть — і саме це вже сталось.
 */

/* ── кого скануємо ───────────────────────────────────────────────────────
 *
 * Обхід РЕКУРСИВНИЙ по всьому дереву `app/`. Плоский `readdirSync(APP)` був
 * дірою, і не теоретичною: усе, що лежить у `app/vendor/`, обидва охоронці
 * i18n (цей і `tests/i18n-keys.test.mjs`) не бачили ВЗАГАЛІ — через це весь
 * текст оверлея інспектора тижнями стояв прибитим до української, поки обидва
 * тести зеленіли. Та сама хвороба, що й у списку дозволу вище: перевірка
 * дивилась не туди, куди переїхав текст.
 *
 * Сам обхід і перелік винятків живуть у `tests/_sources.mjs` (TD-14): доти
 * вони були переписані в кожному охоронці окремо, і саме розходження таких
 * переліків цю дірку й породило. Шляхи приходять ВІДНОСНО `app/`, прямим
 * слешем (`vendor/inspector.js`): саме ними адресуються винятки нижче, і саме
 * так вони читаються в повідомленні про падіння.
 */
const scannedFiles = () =>
  jsFiles().filter((f) => f !== DICT_FILE && !VENDOR_MIN.has(f));

/** Свідок обходу — спільний для обох сканерів цього файла.
 *
 *  Підлоги — ЧИСЛА, а не `files.length`: список, що звіряється сам із собою,
 *  порожнім підтвердив би себе ж, і охоронець лишився б зеленим, не відкривши
 *  жодного файла.
 *
 *  Вікно першої підлоги виміряне з обох боків: сьогодні файлів 24, плоский
 *  обхід давав 18, отже підлога мусить стояти ВИЩЕ за 18 (інакше вона
 *  переживе відкат рекурсії) і НИЖЧЕ за 24 настільки, щоб звичайне прибирання
 *  модуля не давало хибного падіння. Звідси 20 — та сама пропорція запасу, що
 *  в старої підлоги 14 на 18 файлах.
 *
 *  Друга підлога названа окремо й навмисно: вона говорить рівно про ту гілку,
 *  якої плоский обхід не бачив. Самої лише сумарної кількості на це не досить
 *  — `vendor/` можна знову втратити, дописавши кілька файлів просто в `app/`,
 *  і сума не здригнеться. */
function assertReached(files) {
  assert.ok(files.length >= 20,
    `обхід дав лише ${files.length} файлів під app/ — межа знову звузилась`);
  const vendor = files.filter((f) => f.startsWith("vendor/"));
  assert.ok(vendor.length >= 5,
    `у скан не потрапив app/vendor/ (${vendor.length} файлів) — та сама діра, `
    + `крізь яку весь текст оверлея інспектора стояв українською при зелених тестах`);
}

/* Винятки — ВУЖЧІ за файл: кожен назває оголошення, а не «весь модуль».
   Виняток розміром у файл повернув би ту саму дірку, з якої межа щойно
   вивернулась, лише під іншим іменем.
     · `ALIASES` у `shell-palette.js` — синоніми пошуку ⌘K. Кирилиця тут
       СВІДОМО стоїть поруч із латиницею в ОДНОМУ рядку
       («мова language lang»), бо це не напис на екрані, а МІШЕНЬ ПОШУКУ,
       яка мусить збігатись незалежно від мови інтерфейсу: `t()` віддає
       рівно одну, поточну мову, тож у словнику цей рядок перестав би
       робити саме те, для чого існує (шапка `ALIASES` це й документує).
       Той самий клас винятку, що `new RegExp(`…`)` у сканері шаблонів:
       кирилиця як частина ФОРМАТУ ЗБІГУ, не як текст для людини. */
const LITERAL_EXEMPT = [
  { file: "shell-palette.js", decl: /const\s+ALIASES\s*=\s*/ },
  /*   · `measure()` і `between()` у `vendor/inspector-measure.js` — імена
       прямокутників, які лінійка підставляє у власні `throw new Error(…)`
       (`checkRect`), і текст перевірки «список кандидатів має бути масивом».
       Це ДІАГНОСТИКА для того, хто пише код: вона звучить у консолі й лише
       тоді, коли збирач уже подав криві числа, тобто рендер уже зламаний, — до
       дизайнера вона не доходить ніколи. Той самий клас винятку, що
       `throw new Error` у `EXEMPT` сканера шаблонів нижче, і з тієї ж причини:
       у словнику це вдавало б стан продукту, а переклад зробив би саму
       діагностику ГІРШОЮ — інваріант шукають за текстом у сирці.
       Виняток на ОГОЛОШЕННЯ, а не на файл: решта модуля — 500 рядків
       геометрії — лишається під охороною. */
  { file: "vendor/inspector-measure.js", decl: /export function measure\s*\(/ },
  { file: "vendor/inspector-measure.js", decl: /export function between\s*\(/ },
];

test("жодного літерала з кирилицею під app/ (разом із vendor/) — усе через t()", () => {
  const files = scannedFiles();
  const bad = {};
  let examined = 0;
  for (const f of files) {
    const src = blankComments(readSource(f));

    /* Прогалину винятку вирізаємо НЕ забілюванням, а фільтром по позиції:
       забілити `const ALIASES = {…}` означало б прибрати з файла дужки, за
       якими лексер тримає баланс `${…}`, — і решта файла розібралась би
       навскіс. Той самий урок, що й у сканера: калічити сирець перед
       розбором дешево лише поки розбір плоский. */
    const skip = [];
    for (const { file, decl } of LITERAL_EXEMPT) {
      if (file !== f) continue;
      const span = bodySpan(src, decl);
      assert.ok(span,
        `виняток ${decl} більше не знаходиться у ${f} — оголошення перейменували `
        + `чи прибрали, і виняток тепер прикриває невідомо що`);
      skip.push(span);
    }

    const hits = stringLiterals(src)
      .filter((l) => !skip.some(([a, b]) => l.index >= a && l.index < b));
    examined += hits.length;
    const cyr = hits.filter((l) => CYRILLIC.test(l.text))
      .map((l) => `${src.slice(0, l.index).split("\n").length}: ${l.text.slice(0, 70)}`);
    if (cyr.length) bad[f] = cyr.slice(0, 5);
  }

  assert.deepEqual(bad, {},
    `рядки поза словником:\n${JSON.stringify(bad, null, 2)}`);

  /* Свідок проти вакуумного проходу. Він рахує ЗНАЙДЕНІ ЛІТЕРАЛИ, а не
     файли: зламаний `blankComments` (забілив усе) чи зламаний регексп
     літералів дали б рівно нуль збігів — і тест зеленів би, бо шукати вже
     нічого. Файли ж лишились би на місці, тож рахувати їх нічого не
     доводить (рівно ця помилка й стояла у свідка сітки висот
     `tests/css-guards.test.mjs`: рахував розглянуті селектори, а не
     зміряні висоти). Підлога свідомо груба — тут важить лише «не нуль і не
     жменя». Виміряно 1949 літералів на 26 файлах (переміряно 18.09.2026; було 1763 на 24)
     після того, як обхід став
     рекурсивним (було 1368 на 18 плоских); підлога піднята з 800 до 1400,
     інакше вона пережила б утрату всього `vendor/` і перестала б означати
     те, заради чого стоїть. */
  assertReached(files);
  assert.ok(examined > 1400,
    `сканер знайшов лише ${examined} строкових літералів на ${files.length} файлах `
    + `— зламаний регексп чи blankComments, а не «кирилиці нема»`);
});

/* ── шаблонні літерали ───────────────────────────────────────────────────── */

/** Текст шаблонних літералів файла: `[{line, text, before}]`.
 *
 *  Посимвольний розбір, а не регексп, — рівно з тієї причини, через яку
 *  шаблони колись і винесли за межу перевірки: вкладений `${…}` містить
 *  власні лапки й власні дужки, і жоден регексп не рахує вкладення. Тут
 *  вкладення рахується дужками: усе між `${` і парною `}` викидається, у
 *  тексті лишається сам шаблон. `before` — сирець ПЕРЕД відкривним апострофом
 *  (для двох винятків нижче), `line` — номер рядка для повідомлення. */
function templates(src) {
  const out = [];
  for (let i = 0; i < src.length; i += 1) {
    if (src[i] !== "`") continue;
    const open = i;
    const text = [];
    i += 1;
    while (i < src.length) {
      const c = src[i];
      if (c === "\\") { i += 2; continue; }
      if (c === "`") break;
      if (c === "$" && src[i + 1] === "{") {
        let depth = 1;
        i += 2;
        while (i < src.length && depth > 0) {
          if (src[i] === "{") depth += 1;
          else if (src[i] === "}") depth -= 1;
          i += 1;
        }
        continue;
      }
      text.push(c);
      i += 1;
    }
    out.push({
      line: src.slice(0, open).split("\n").length,
      text: text.join(""),
      before: src.slice(Math.max(0, open - 40), open),
    });
  }
  return out;
}

/* Три винятки, і жоден — НЕ «тут незручно перекладати», а всі три — «переклад
   тут зламав би роботу»:
     · `new RegExp(`…`)` — розбирає те, що написав сервер. `label_text` із
       `serve.py` завжди українською незалежно від мови інтерфейсу, тож
       кирилиця в ШАБЛОНІ ПОШУКУ — частина формату даних, а не текст для
       людини. Замінити її на `t()` значить у English-режимі шукати «It.3»
       у рядку «Іт.3 · Правки» й лишити примітку з префіксом усередині.
     · `throw new Error(`…`)` — текст падіння для того, хто пише код. Він
       ніколи не доходить до дизайнера (кидає лише невідома іконка чи
       невідомий ключ — тобто вже зламаний рендер), а в словнику зробив би
       вигляд, ніби це стан продукту.
     · `checkRect(rect, …)` (`vendor/inspector-measure.js`) — імʼя
       прямокутника, яке та сама `checkRect` через рядок підставляє у власний
       `throw new Error(…)`. Тобто це попередній виняток, лише зібраний на
       виклик раніше: імʼя «кандидат #N» мусить бути шаблоном, бо в ньому
       стоїть номер. Решта імен того модуля — звичайні рядки, і вони виписані
       окремо, у `LITERAL_EXEMPT`: їх бачить ІНШИЙ сканер.
       Вузькість тут не менша за оголошення, а більша: виняток привʼязаний до
       конкретного виклику. */
const EXEMPT = [
  /new RegExp\(\s*$/,
  /throw new Error\(\s*$/,
  /\bcheckRect\([^()]*,\s*$/,
];

test("шаблонні літерали під app/ (разом із vendor/): жодної кирилиці — усе через t()", () => {
  const files = scannedFiles();
  const bad = [];
  let seen = 0;
  for (const f of files) {
    const src = blankComments(readSource(f));
    for (const tpl of templates(src)) {
      seen += 1;
      if (!CYRILLIC.test(tpl.text)) continue;
      if (EXEMPT.some((re) => re.test(tpl.before))) continue;
      bad.push(`${f}:${tpl.line}  \`${tpl.text.trim().slice(0, 60)}\``);
    }
  }
  assert.deepEqual(bad, [],
    `кирилиця в шаблонних літералах:\n${bad.join("\n")}`);

  /* Свідок. Досі його тут не було взагалі — сканер шаблонів міг не знайти
     жодного шаблону й мовчки зеленіти, бо `bad` лишався порожнім саме тоді,
     коли дивитись уже не було на що. Рахуються ЗНАЙДЕНІ ШАБЛОНИ, не файли:
     зламаний посимвольний розбір дав би нуль при повному списку файлів.
     Виміряно 322 шаблони на 26 файлах (переміряно 18.09.2026; було 272 на 24). */
  assertReached(files);
  assert.ok(seen > 200,
    `сканер знайшов лише ${seen} шаблонних літералів на ${files.length} файлах `
    + `— зламаний розбір templates() чи blankComments, а не «кирилиці нема»`);
});
