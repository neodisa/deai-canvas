/**
 * «Налаштування → AGENTS.md» (етап Е, 0.31.0, Task 6) — живе проведення: справжній сервер в ізольованій «машині»
 * (тимчасові `HOME`/`DEAI_HOME`; теки просторів — під ними), справжній Chromium. Юніти доводять розмітку й проводку; тут те, що
 * живе лише з сервером і браузером: застарілий блок → плашка й крапка в навігації → «Оновити з шаблону» переписує БЛОК на диску,
 * а «Ваше» (до й після) лишає байт-у-байт; нема файла → «Створити»; файл новішого Deai → «Оновити» неактивна й файл цілий;
 * «Скопіювати» дає тост і кладе в буфер текст файла.
 *
 * Мапа «сценарій → запобіжник» (мутаційно):
 *   1 (крапка + плашка)         — `agentsOutdated` у `navItems`/`setNavHTML`, `loadAgents()` у `loadConn`.
 *   1 (оновлення на диску)      — `agentsWrite` (POST) і `agents_md.write` (збереження «Ваше»); тост `agUpdated`; фокус — `focusAgents`.
 *   2 (створити)                — кнопка `create`, тост `agCreated`.
 *   3 (новіший)                 — `canUpdate`/плашка `agNewerNote`; кнопка `disabled`.
 *   4 (копіювання)              — `agentsCopy`: `writeText` синхронно з кліку, тост `agCopied`.
 */
import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { chromium } from "playwright";
import { VIEW, guardRealDeai, stop, waitBarReady } from "./_spaces-kit.mjs";
import { startServer, taskFixture } from "./fixture.mjs";

const PORT_BASE = 29000;
const MOCKUP = () => "<!doctype html><html><body><h1>Макет</h1></body></html>";
const OLD_BLOCK = "<!-- deai:begin v0.1.0 · generated by Deai Canvas; edit outside this block -->\n## Старий текст шаблону\n- застарілий рядок\n<!-- deai:end -->\n";
const BEFORE = "# Мої нотатки\n- перед блоком, <b>не розмітка</b>\n\n";
const AFTER = "\n## Команда\n- після блоку\n";

let browser;
test.before(async () => { browser = await chromium.launch(); });
test.after(async () => { await browser?.close(); });

/** `file(dir)` — що покласти в AGENTS.md простору до старту сторінки (`null` — нічого). */
async function boot(t, portBase, file) {
  const X = taskFixture({ html: MOCKUP });
  const server = await startServer(null, {
    portBase,
    spaces: [{ name: "Studio", id: "studio", color: "space-2", tasks: { t1: { dir: X.dir, title: "Задача" } } }],
  });
  t.after(() => stop(server.child));
  const target = path.join(server.spaces[0].path, "AGENTS.md");
  if (file !== null) writeFileSync(target, file);
  const context = await browser.newContext({ viewport: VIEW });
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  t.after(() => context.close());
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e.message ?? e)));
  await page.goto(`${server.url}/app/`);
  await waitBarReady(page, 15000);
  return { ...server, page, errors, target };
}

const gear = async (page) => {
  await page.click('[data-act="settings"]');
  await page.waitForSelector(".set-nav", { timeout: 15000 });
};
const toAgents = async (page) => {
  await page.click('.set-nav [data-v="agents"]');
  await page.waitForFunction(() => document.querySelector('.set-nav .nav-i[aria-current="page"]')?.dataset.v === "agents");
};
const dot = (page) => page.locator('.set-nav [data-v="agents"] .set-dotb').count();
const toastText = (page) => page.locator("#cv-toast.show").textContent({ timeout: 8000 });
const api = async (server) => (await fetch(`${server.url}/api/agents-md?space=studio`)).json();

test("1: застарілий блок — плашка й крапка в навігації; «Оновити з шаблону» міняє блок на диску, «Ваше» лишається байт-у-байт", async (t) => {
  const server = await boot(t, PORT_BASE, `${BEFORE}${OLD_BLOCK}${AFTER}`);
  const { page, errors, target } = server;
  await gear(page);
  await page.waitForSelector('.set-nav [data-v="agents"] .set-dotb', { timeout: 15000 });   // крапка — ще з «Модулів»
  await toAgents(page);
  await page.waitForSelector(".note", { timeout: 15000 });
  const live = await api(server);
  assert.equal(live.outdated, true, "сервер вважає блок застарілим (фікстура справді стара)");
  assert.equal((await page.locator(".note p").textContent()).trim(), `Шаблон Deai ${live.version} новіший за цей файл (0.1.0).`);
  assert.equal(await page.locator('[data-th="ag"][data-v="update"]:not([disabled])').count(), 2, "кнопка в голові й у плашці активні");
  assert.match(await page.locator(".ag-own pre").textContent(), /перед блоком, <b>не розмітка<\/b>[^]*після блоку/, "«Ваше» показане текстом, а не розміткою");
  assert.equal(await page.locator(".ag-own pre b").count(), 0, "вміст файла екранований");
  assert.match(await page.locator(".ag-part:not(.ag-own) pre").textContent(), /Старий текст шаблону/);

  await page.click('.th-head [data-th="ag"][data-v="update"]');
  assert.equal((await toastText(page)).trim(), "AGENTS.md оновлено · ваші нотатки на місці");
  await page.waitForFunction(() => !document.querySelector(".note"), null, { timeout: 15000 });
  assert.equal(await dot(page), 0, "крапки нема");
  assert.equal(await page.locator('[data-th="ag"][data-v="update"]:not([disabled])').count(), 0, "актуальний — «Оновити» неактивна");
  assert.equal(await page.evaluate(() => document.activeElement?.dataset?.v), "copy", "фокус не загубився: на «Скопіювати»");

  const after = await api(server);
  assert.equal(after.outdated, false);
  assert.equal(after.fileVersion, after.version);
  const disk = readFileSync(target, "utf8");
  assert.equal(disk, `${BEFORE}${after.block}${AFTER}`, "«Ваше» до й після — байт-у-байт, між ними — новий блок");
  assert.doesNotMatch(disk, /Старий текст шаблону|застарілий рядок/);
  assert.match(await page.locator(".ag-part:not(.ag-own) .ag-g").textContent(), new RegExp(`З шаблону · Deai ${after.version.replace(/\./g, "\\.")}`));
  assert.deepEqual(errors, []);
});

test("2: простору без AGENTS.md — «Створити» пише файл; «Ваше» порожнє, частину не показано", async (t) => {
  const server = await boot(t, PORT_BASE + 10, null);
  const { page, errors, target } = server;
  assert.equal(existsSync(target), false);
  await gear(page);
  await toAgents(page);
  await page.waitForSelector('[data-th="ag"][data-v="create"]', { timeout: 15000 });
  assert.match(await page.locator(".ag-empty").textContent(), /AGENTS\.md ще нема/);
  assert.equal(await page.locator(".th-head .ag-acts").count(), 0, "кнопок голови нема, поки нема файла");
  assert.equal(await dot(page), 0);

  await page.click('[data-th="ag"][data-v="create"]');
  assert.equal((await toastText(page)).trim(), "AGENTS.md створено");
  await page.waitForSelector(".ag", { timeout: 15000 });
  const live = await api(server);
  assert.equal(readFileSync(target, "utf8"), live.block, "файл = згенерований блок");
  assert.equal(await page.locator(".ag-own").count(), 0, "порожнє «Ваше» не показуємо");
  assert.equal(await page.locator('.th-head [data-v="update"][disabled]').count(), 1, "актуальний — «Оновити» неактивна");
  assert.equal(await page.evaluate(() => document.activeElement?.dataset?.v), "copy");
  assert.deepEqual(errors, []);
});

test("3: файл із новішого Deai — плашка «оновіть Deai», обидві «Оновити» неактивні, файл не чіпається", async (t) => {
  const newer = "<!-- deai:begin v9.9.9 · generated by Deai Canvas; edit outside this block -->\n## З майбутнього\n<!-- deai:end -->\n";
  const file = `${BEFORE}${newer}${AFTER}`;
  const server = await boot(t, PORT_BASE + 20, file);
  const { page, errors, target } = server;
  await gear(page);
  await toAgents(page);
  await page.waitForSelector(".note", { timeout: 15000 });
  assert.equal((await page.locator(".note p").textContent()).trim(), "Цей блок записав новіший Deai (9.9.9) — оновіть Deai.");
  assert.equal(await page.locator('[data-th="ag"][data-v="update"]').count(), 2);
  assert.equal(await page.locator('[data-th="ag"][data-v="update"]:not([disabled])').count(), 0, "обидві неактивні");
  assert.equal(await dot(page), 0, "новіший — не «застарілий»: крапки нема");
  await page.locator('.note [data-v="update"]').click({ force: true });
  await page.waitForTimeout(300);
  assert.equal(readFileSync(target, "utf8"), file, "файл не змінився");
  assert.deepEqual(errors, []);
});

test("4: «Скопіювати» кладе показаний текст (блок + «Ваше») в буфер і каже тостом; копіювання шляху — окремий тост", async (t) => {
  const server = await boot(t, PORT_BASE + 30, `${BEFORE}${OLD_BLOCK}${AFTER}`);
  const { page, errors, target } = server;
  await gear(page);
  await toAgents(page);
  await page.waitForSelector(".ag", { timeout: 15000 });
  await page.click('.th-head [data-v="copy"]');
  assert.equal((await toastText(page)).trim(), "AGENTS.md скопійовано");
  const live = await api(server);
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), live.block + live.own, "буфер = те, що показано: блок, потім «Ваше»");
  await page.waitForFunction(() => !document.querySelector("#cv-toast.show"), null, { timeout: 15000 });
  await page.click('.ag-bar [data-v="copypath"]');
  assert.equal((await toastText(page)).trim(), "Шлях скопійовано");
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), target);
  assert.deepEqual(errors, []);
});

guardRealDeai();
