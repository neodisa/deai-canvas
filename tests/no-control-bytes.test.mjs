import assert from "node:assert/strict";
import test from "node:test";

import { readSource, sourceFiles } from "./_sources.mjs";

/*
 * Один сирий керуючий байт робить джерельний файл БІНАРНИМ — і кожна перевірка,
 * побудована на `grep`, починає його тихо пропускати. Не падати, не скаржитись:
 * пропускати. Це найгірший вид сліпоти охоронця, бо він виглядає як «зелено».
 *
 * Знайдено 03.09.2026: `app/ext-shell.js` мав сирий NUL посеред шаблонного
 * літерала (`worldKey`, розділювач ключа кеша). Наслідки, виміряні:
 *   · `file(1)` називав модуль на 969 рядків просто «data»;
 *   · `grep -n "export" app/ext-shell.js` вертав НІЧОГО з кодом виходу 0;
 *   · JS при цьому парсився й працював, тести були зелені — тобто ніщо, крім
 *     випадкового `file`, про це не сказало б.
 *
 * Node-охоронці (`i18n-literals`, `icons`, `i18n-keys`) читають файли самі й
 * від цього не страждають — але вони не єдині, хто дивиться в `app/`, і не
 * зобовʼязані лишатись єдиними.
 *
 * Межа перевірки записана свідомо: дозволені `\t`, `\n`, `\r` — усе інше з
 * C0-діапазону й `\x7f` (DEL) заборонені. Символи вище U+007F не чіпаємо: у
 * цьому репозиторії коментарі українською, і кирилиця тут законна.
 */
const ALLOWED = new Set([0x09, 0x0a, 0x0d]);
const forbidden = (code) => (code < 0x20 && !ALLOWED.has(code)) || code === 0x7f;

/* Обхід РЕКУРСИВНИЙ по всьому дереву `app/`. Плоский `readdirSync(APP)` не
   бачив ЖОДНОГО з восьми файлів під `app/vendor/` — разом із двома, що
   зʼявились на цій гілці. Та сама діра, що її щойно залатали обидва охоронці
   i18n (`tests/i18n-literals.test.mjs`, там ця історія розписана), але тут
   вона дорожча: сліпота цього охоронця означає не «текст лишився без
   перекладу», а «файл став бінарним, і кожна перевірка на grep тихо його
   пропускає» — рівно те, що вже сталось із `app/ext-shell.js` вище.

   Сам обхід тепер спільний (`tests/_sources.mjs`, TD-14) — рівно тому, що
   дірка, яку він закриває, і взялася з трьох незалежних копій цього обходу.
   `sourceFiles`, а не `jsFiles`: тут питання не про авторство тексту, а про
   те, чи лишається файл ТЕКСТОМ, — а це властивість і таблиці стилів. */

/* ── чому мініфіковані чужі бандли ТУТ у скані ───────────────────────────
 *
 * Охоронці i18n виносять `vendor/*.min.js` за межу скану, і правильно роблять:
 * там питання про АВТОРСТВО ТЕКСТУ — ми не пишемо й не перекладаємо чужих
 * рядків, і в мініфікованому бандлі немає чого класти у словник.
 *
 * Тут питання інше й про інше: чи лишається файл ТЕКСТОМ для наших
 * інструментів. Це властивість самого файла, не його автора. Сирий NUL
 * усередині `comment-layer.min.js` робить бінарним 65 КБ, які лежать у НАШОМУ
 * репозиторії, які читає НАШ `grep`/`git grep`/`file(1)` і які ми викладаємо
 * на прод. Те, що ми не полагодили б це правкою у файлі (полагодили б
 * перекачуванням бандла або відмовою прийняти цю поставку), межі скану не
 * змінює: робота охоронця — СКАЗАТИ, а не бути виправним на місці.
 *
 * Мініфікований бандл ще й найгірше місце для такої сліпоти: його ніхто не
 * читає очима, тож саме там вона протрималась би найдовше.
 *
 * Ціна виміряна й дорівнює нулю: обидва бандли сьогодні чисті (0 керуючих
 * байтів на 68 634 символи), тож включення не додає ні падінь, ні винятків.
 */

/* ── єдиний вендорений виняток ───────────────────────────────────────────
 *
 * `modules/supabase-comments/supabase.min.js` — `@supabase/supabase-js` 2.110.0 (UMD), чужий код БЕЗ ЗМІН (його SHA-256
 * приколотий у `tests/test_supabase_comments.py`: перекладати його «на екранування» значило б віддати не ту збірку, яку
 * випустив автор). У двох шаблонних літералах (`join(\`<U+001F>\`)`, склеювання ключів) він має сирий U+001F — не NUL, тож
 * файл лишається ТЕКСТОМ для наших інструментів: `file(1)` каже «ASCII text», `grep` його читає (виміряно під час
 * вендорення). Тому виняток якнайвужчий: ОДИН файл, ОДИН код, ТОЧНА кількість. Інший байт у ньому, інший код, більше чи
 * менше цих двох (збірку замінили іншою) — падіння: виняток не дає вендореному файлу нічого, окрім цих двох байтів. */
const VENDORED = new Map([["modules/supabase-comments/supabase.min.js", { code: 0x1f, count: 2 }]]);

test("у джерелах app/ немає сирих керуючих байтів — інакше grep їх не бачить", () => {
  const files = sourceFiles();
  const bad = [];
  let scanned = 0;
  for (const f of files) {
    const src = readSource(f);
    scanned += src.length;
    const allowed = VENDORED.get(f);
    let allowedSeen = 0;
    for (let i = 0; i < src.length; i += 1) {
      const code = src.charCodeAt(i);
      if (!forbidden(code)) continue;
      if (allowed && code === allowed.code) { allowedSeen += 1; continue; }
      const line = src.slice(0, i).split("\n").length;
      const col = i - (src.lastIndexOf("\n", i - 1) + 1);
      bad.push(`${f}:${line}:${col} — U+${code.toString(16).padStart(4, "0").toUpperCase()}`);
    }
    if (allowed && allowedSeen !== allowed.count) {
      bad.push(`${f} — виняток вендореного файла (рівно ${allowed.count} × U+${allowed.code.toString(16).padStart(4, "0").toUpperCase()}) `
        + `застарів: знайдено ${allowedSeen}`);
    }
  }
  assert.deepEqual(bad, [],
    "сирий керуючий байт у джерелі: файл стає бінарним, і перевірки на grep "
    + `його ТИХО пропускають. Пиши екранування (\\u0000), не сам байт:\n${bad.join("\n")}`);

  /* ── свідки ────────────────────────────────────────────────────────────
     Досі їх тут не було зовсім, а цей охоронець вразливий до вакуумного
     проходу найбільше: `bad` порожній і тоді, коли все чисто, і тоді, коли не
     відкрито жодного файла. Саме так він і прожив усе життя — не бачачи
     `vendor/` і зеленіючи.

     Обидві підлоги виміряні з двох боків — вище за те, що дає плоский обхід,
     і нижче за сьогоднішнє значення настільки, щоб звичайне прибирання коду
     не давало хибного падіння:
       · файли: 28 сьогодні, 20 при плоскому обході → 24;
       · символи: 764 598 (переміряно 18.09.2026; було 659 313 до винесення
         `esc.js` і спільного `_sources.mjs`), 480 173 при плоскому обході → 520 000.
     Рахуються саме СИМВОЛИ, а не файли: зламане читання дало б повний список
     файлів і нуль перевіреного змісту.

     Третій свідок названий окремо, бо говорить рівно про ту гілку, якої
     плоский обхід не бачив: суму можна добрати файлами в самому `app/`. */
  assert.ok(files.length >= 24,
    `обхід дав лише ${files.length} джерел під app/ — межа знову звузилась`);
  assert.ok(scanned > 520000,
    `перевірено лише ${scanned} символів на ${files.length} файлах — зламане `
    + `читання, а не «керуючих байтів нема»`);
  const vendor = files.filter((f) => f.startsWith("vendor/"));
  assert.ok(vendor.length >= 5,
    `у скан не потрапив app/vendor/ (${vendor.length} файлів) — саме там сліпота `
    + `тримається найдовше, бо мініфікований бандл ніхто не читає очима`);
});
