import assert from "node:assert/strict";
import test from "node:test";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { APP, VENDOR_MIN, jsFiles } from "./_sources.mjs";

/**
 * КОЖЕН модуль під `app/` має парситись. Здається банальним — але саме цього
 * охоронця тут не було, і ціна вимірялась.
 *
 * ⛔ ІНЦИДЕНТ (22.09.2026, T-40). У `app/vendor/inspector.js` таблиця стилів
 * оверлея лежить ШАБЛОННИМ ЛІТЕРАЛОМ (`const STYLE = ...`). Коментар,
 * дописаний усередину неї, містив зворотні апострофи навколо імен класів — і
 * перший із них обірвав літерал. Модуль перестав парситись цілком, тобто
 * `CanvasInspector` у документі макета просто не зʼявлявся: ні інспектора, ні
 * тюнера, ні лінійки.
 *
 * ⚠️ І ВСІ 556 ЮНІТІВ ЛИШИЛИСЬ ЗЕЛЕНИМИ. Цей файл чіпає `document` уже на
 * імпорті, тож жоден юніт його не імпортує — охоронець css-guards читає його
 * ТЕКСТОМ і регекспом, а текст зіпсованого файла анітрохи не гірший за текст
 * справного. Знайшов це живий тест, тобто найдорожчий і найповільніший із
 * наявних інструментів, і знайшов повідомленням «таймаут 15000мс», з якого
 * причина не читається зовсім.
 *
 * Тому перевірка й формулюється найгрубіше з можливих: не «чи правильний
 * код», а «чи це взагалі JavaScript». Вона коштує секунду й ловить цілий клас
 * поломок, які інакше доїжджають до браузера дизайнера.
 *
 * Мініфіковані чужі бандли теж у скані: питання «чи парситься» — про файл, а
 * не про його автора (той самий доказ, що в `tests/no-control-bytes.test.mjs`).
 * VENDOR_MIN тут лежить лише для того, щоб було видно, що виняток розглянули
 * і НЕ зробили.
 */
test("кожен .js під app/ парситься — інакше він мовчки не піднімається в браузері", () => {
  const files = jsFiles();
  assert.ok(files.length > 15,
    `обхід знайшов лише ${files.length} модулів — зламаний, а не «нема чого перевіряти»`);
  assert.ok(files.some((f) => VENDOR_MIN.has(f)),
    "чужі бандли випали зі скану: питання «чи парситься» — про файл, не про автора");
  const broken = [];
  for (const rel of files) {
    const r = spawnSync(process.execPath, ["--check", path.join(APP, rel)],
      { encoding: "utf8" });
    if (r.status !== 0) broken.push(`${rel}: ${(r.stderr || "").split("\n")[2] || ""}`);
  }
  assert.deepEqual(broken, [],
    `модулі, які не парсяться (у браузері їх просто не буде):\n${broken.join("\n")}`);
});
