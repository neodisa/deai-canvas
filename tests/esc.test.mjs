import assert from "node:assert/strict";
import test from "node:test";

import { esc } from "../app/esc.js";
import { VENDOR_MIN, jsFiles, readSource, stripComments } from "./_sources.mjs";

/*
 * Охоронець єдиного джерела екранування (TD-12, закрито 18.09.2026).
 *
 * До цієї правки `esc` було оголошено в `app/` ВІСІМ разів: сім побайтово
 * однакових копій в оболонці й ширша (з апострофом) в оверлеї. Нічого не
 * звіряло, що вони збігаються, — тобто правка в одній копії, забута в решті,
 * не червоніла ніде. Ціна такого розходження названа в записі боргу прямо:
 * XSS в одній поверхні з восьми, знайдений на макеті колеги, а не в прогоні.
 *
 * ⛔ Тому нижче стоять ДВА різні охоронці, і плутати їх не можна:
 *   · перший міряє ПОВЕДІНКУ спільної функції — що саме вона екранує;
 *   · другий міряє СТРУКТУРУ — що другої копії не зʼявилось. Без нього
 *     поведінковий лишився б зеленим і тоді, коли половина модулів
 *     екранується власною, зламаною функцією: він її просто не бачить.
 */

/* Обхід дерева, перелік чужих бандлів і забілювання коментарів — спільні
   (`tests/_sources.mjs`). Чужий мініфікований код за межею з тієї самої
   причини, що в обох охоронців i18n: ми його не пишемо, і таблиця екранування
   всередині чужого бандла не є НАШОЮ копією. */
const SHARED = "esc.js";
const sources = () =>
  jsFiles().filter((f) => !VENDOR_MIN.has(f))
    .map((f) => ({ file: f, src: stripComments(readSource(f)) }));

/* ── 1. поведінка ─────────────────────────────────────────────────────── */

test("екранує рівно чотири символи розмітки", () => {
  assert.equal(esc('<img src=x onerror="a">'), "&lt;img src=x onerror=&quot;a&quot;&gt;");
  assert.equal(esc("&"), "&amp;");
});

test("амперсанд екранується ПЕРШИМ — інакше екранування зʼїдає саме себе", () => {
  /* `<` → `&lt;`; якби `&` оброблявся після, вийшло б `&amp;lt;` і дизайнер
     побачив би на екрані текст «&lt;», а не «<». */
  assert.equal(esc("<"), "&lt;");
  assert.equal(esc("&lt;"), "&amp;lt;");
});

test("апостроф НЕ екранується — межа записана, а не забута", () => {
  /* Атрибути в розмітці оболонки пишуться подвійними лапками, тож апостроф
     звідти не виводить. Хто потребує ширшого набору — будує його ПОВЕРХ
     (`app/vendor/inspector.js`), і саме це перевіряє тест нижче. */
  assert.equal(esc("don't"), "don't");
});

test("null і undefined дають порожньо, а не слово «null»", () => {
  assert.equal(esc(null), "");
  assert.equal(esc(undefined), "");
  assert.equal(esc(0), "0", "нуль — це значення, а не порожнеча");
});

/* ── 2. структура: другої копії немає ─────────────────────────────────── */

test("таблиця екранування оголошена рівно в одному нашому файлі", () => {
  const files = sources();
  const owners = files.filter(({ src }) => src.includes("&amp;")).map(({ file }) => file);
  assert.deepEqual(owners, [SHARED],
    `таблицю екранування переписали ще раз: ${owners.join(", ")}. Саме так `
    + `зʼявились вісім копій, які TD-12 і закривав`);

  /* Свідок: підлога — ЧИСЛО, а не `files.length`. Список, звірений сам із
     собою, порожнім підтвердив би себе ж — і охоронець лишився б зеленим, не
     відкривши жодного файла. Вікно виміряне з ОБОХ боків, як у сусідніх
     охоронців: 27 файлів сьогодні, 21 при плоскому обході (тобто без
     `vendor/`). Тому підлога 24 — ВИЩЕ за плоский обхід (інакше вона пережила б
     відкат рекурсії й нічого не сказала) і нижче за сьогоднішнє настільки, щоб
     звичайне прибирання модуля не давало хибного падіння. Перша редакція
     стояла на 20 і цю вимогу НЕ виконувала: плоский обхід проходив би її
     зеленим, і весь тягар лягав на свідка `vendor/` нижче — тобто на одного
     замість двох. */
  assert.ok(files.length >= 24,
    `обхід дав лише ${files.length} файлів під app/ — межа звузилась`);
  const vendor = files.filter(({ file }) => file.startsWith("vendor/"));
  assert.ok(vendor.length >= 5,
    `у скан не потрапив app/vendor/ (${vendor.length}) — а восьма копія жила `
    + `саме там`);
});

test("кожен, хто кличе esc(), бере його зі спільного модуля", () => {
  const files = sources();
  const IMPORT = /import\s*\{[^}]*\besc\b[^}]*\}\s*from\s*["']\.\.?\/esc\.js["']/;
  const callers = [];
  const rogue = [];
  for (const { file, src } of files) {
    if (file === SHARED || !/\besc\(/.test(src)) continue;
    callers.push(file);
    if (!IMPORT.test(src)) rogue.push(file);
  }
  assert.deepEqual(rogue, [],
    `${rogue.join(", ")} кличе esc(), не імпортуючи його: це або власна копія, `
    + `або власна ЗЛАМАНА копія — і зовні ці два випадки не відрізняються`);

  /* Свідок: підлога на кількість КЛИКАЧІВ. Без неї регексп, що перестав ловити
     виклики, дав би порожній `rogue` і зелений тест — тобто «порушень немає»
     від того, що нічого не перевірено. Сьогодні кликачів 8. */
  assert.ok(callers.length >= 7,
    `знайдено лише ${callers.length} модулів, що кличуть esc() — регексп не працює`);
});

/* ── 3. ширший esc оверлея лишається НАДБУДОВОЮ, а не копією ──────────── */

test("esc оверлея зібраний ПОВЕРХ спільного, а не переписаний", () => {
  const src = stripComments(readSource("vendor/inspector.js"));
  assert.match(src, /return escHTML\(v\)\.replace\(\/'\/g, '&#39;'\);/,
    "оверлей перестав будувати своє екранування поверх спільного — перевір, "
    + "чи не зʼявилась знову власна таблиця символів");
});

test("надбудова дає ТОЙ САМИЙ вихід, що однопрохідна таблиця до TD-12", () => {
  /* Еталон — саме той код, який лежав в `inspector.js` до виносу. Тест боронить
     контракт: після заміни таблиці на склейку вихід не сміє зрушити ні на
     байт, інакше тултипи оверлея тихо змінили б вигляд. Ключова тонкість, яку
     він і міряє: `&` всередині `&#39;` зʼявляється ПІСЛЯ `escHTML`, тож
     повторно не екранується. */
  const TABLE = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
  const legacy = (v) => String(v == null ? "" : v).replace(/[&<>"']/g, (c) => TABLE[c]);
  const composed = (v) => esc(v).replace(/'/g, "&#39;");

  const cases = ["&<>\"'", "a&'b", "don't <b>", "", null, undefined, 0,
    "&amp;", "&#39;", "class=\"x\" id='y'"];
  for (const c of cases) {
    assert.equal(composed(c), legacy(c), `розійшлись на ${JSON.stringify(c)}`);
  }
});
