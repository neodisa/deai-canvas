import assert from "node:assert/strict";
import test from "node:test";

import { DICT } from "../app/i18n.js";
import { DICT_FILE, VENDOR_MIN, jsFiles, readSource } from "./_sources.mjs";

/* Обхід РЕКУРСИВНИЙ по всьому дереву `app/`, а не плоский `readdirSync(APP)`.
   Плоский був дірою, і виміряною: `app/vendor/` цей охоронець не бачив узагалі
   — рівно як і охоронець літералів (`tests/i18n-literals.test.mjs`, там ця
   історія розписана). `app/vendor/insp-report.js` — перший файл під `vendor/`,
   який кличе `t()`, тож ставка тут тепер жива, а не лише принципова.
   Шляхи — ВІДНОСНО `app/`, прямим слешем (`vendor/insp-report.js`).

   Словник — місце тексту, а не виклику; два мініфіковані файли — чужий код,
   який ми не пишемо й ключі якого до нашого словника стосунку не мають.
   Обидва переліки й сам обхід приїжджають із `tests/_sources.mjs` (TD-14):
   доти вони були переписані тут окремо, і «збігаються з i18n-literals»
   трималось на слові в цьому ж коментарі — рівно те, що розходиться мовчки. */

/* Ловить одруки статично: інакше `t('vpTablte')` виявиться лише коли цей
   код-шлях відпрацює — у гіршому разі під час роботи, а не в тесті. Межа
   перевірки записана свідомо: регексп вимагає, щоб ключ починався з
   ЛАТИНСЬКОЇ літери й був літералом. Три речі поза межею методу, і всі три
   записані свідомо:
     · `t(key)` зі змінною і `t(`…`)` з шаблоном — статично не проверяються;
     · ключ, написаний кирилицею, регексп не бачить узагалі. Це не діра:
       ключі словника всі латиницею (`vpTablet`), тож реальний одрук теж буде
       латиницею — а кириличний «ключ» кинув би на першому ж рендері, бо
       `t()` кидає на невідомому ключі. Знайдено тим, що приклад мутації в
       плані був написаний кирилицею і НЕ валив цей тест.

   Друге джерело (Task 8 review, п.3): `app/bar-model.js` не кличе `t()`
   узагалі — він віддає ІМЕНА ключів рядком у полях `labelKey`/`whyKey`/
   `subKey`, а `t()` кличе вже DOM-шар Плану B. Перший регексп цього
   структурно не бачить — тест був би сліпим саме до того модуля, заради
   якого написаний. Тому другий прохід сканує ці поля тим самим правилом
   «перший символ — латиниця» — АЛЕ решту літералу не звужує до `\w`: `\w` у
   JS без прапорця `u` бере лише ASCII, і токен на кшталт `whyНемаТакого`
   (латиниця, далі кирилиця) обірвав би збіг одразу після «why», тихо
   пропустивши одрук — рівно так само, як «повністю кириличний ключ»
   пропускає перший регексп. Тут ця діра НЕ бажана: `labelKey`/`whyKey`/
   `subKey` — робочі рядки самого коду, а не текст, що показується
   користувачу, і мішаний одрук у них — реальний ризик, не гіпотетичний.

   Межа лишається та сама, що й у першого проходу: значення, зібране зі
   ЗМІННОЇ чи тернарника (`whyKey: flowWhy`, `labelKey: s.published ?
   "update" : "publish"`), регексп не бачить — лише прямий літерал у самому
   полі. Кожен такий ключ (`whyNoFlow`, `update`, `glSync`…) усе одно мусить
   лежати в словнику: за це відповідає не регексп, а `t()`, що кидає виняток
   на невідомому ключі в рантаймі — той самий контракт, що й для `t(key)` зі
   змінною вище. */
test("кожен ключ, який кличе код, є у словнику", () => {
  const files = jsFiles().filter((f) => f !== DICT_FILE && !VENDOR_MIN.has(f));
  const used = new Map();
  let vendorHits = 0;
  for (const f of files) {
    const src = readSource(f);
    let hits = 0;
    for (const m of src.matchAll(/\bt\(\s*['"]([A-Za-z][\w-]*)['"]/g)) {
      used.set(m[1], f);
      hits += 1;
    }
    for (const m of src.matchAll(/\b(?:labelKey|whyKey|subKey)\s*:\s*['"]([A-Za-z][^'"]*)['"]/g)) {
      used.set(m[1], f);
      hits += 1;
    }
    if (f.startsWith("vendor/")) vendorHits += hits;
  }

  const missing = [...used].filter(([k]) => DICT.uk[k] === undefined);
  assert.deepEqual(missing, [], `ключі, яких немає у словнику: ${JSON.stringify(missing)}`);

  /* ── свідки ────────────────────────────────────────────────────────────
     Старий свідок був `used.size > 0` — підлога, яку тримав ОДИН уцілілий
     виклик у всьому дереві: регексп, що зламався на 99%, лишався б зеленим.
     Виміряно 213 ключів на 26 файлах (переміряно 18.09.2026; було 200 на 24 —
     зсунули `esc.js` і спільний `_sources.mjs`; плоский обхід давав 198 на 18), тож
     підлога 150 лишає запас на звичайне прибирання ключів і при цьому
     означає «сканер справді пройшов по коду».

     Підлога файлів — ЧИСЛО, а не `files.length`: список, звірений сам із
     собою, порожнім підтвердив би себе ж. Вікно те саме, що в
     `tests/i18n-literals.test.mjs`: 26 файлів сьогодні, 18 при плоскому
     обході, тож 20 — вище за відкат рекурсії й нижче за звичайне прибирання
     модуля.

     Третій свідок названий окремо, бо говорить рівно про ту гілку, якої
     плоский обхід не бачив: у `vendor/` СЬОГОДНІ живуть чотири літеральні
     виклики (`inspector.js` і `insp-report.js`), і вище за одиницю підлогу
     тут ставити нема за що — прибрати один виклик це звичайна правка, а
     сказати цей свідок мусить одне: «до vendor/ дійшли». */
  assert.ok(used.size > 150,
    `знайдено лише ${used.size} ключів на ${files.length} файлах — регексп не працює`);
  assert.ok(files.length >= 20,
    `обхід дав лише ${files.length} файлів під app/ — межа знову звузилась`);
  assert.ok(vendorHits > 0,
    "у app/vendor/ не знайдено жодного виклику t('…') — обхід туди не дійшов, "
    + "а саме крізь цю діру текст інспектора й лишався поза словником");
});

/* Мітки задач (4b-3): нові ключі — в обох мовах рядками (крім підпису кнопки з ключем задачі), а колишні підписи профілів
   зникли зі словника й з коду: чипи напрямків тепер — самі мітки, їхній текст не перекладається. */
test("мітки задач: нові ключі є в обох мовах; profUnited/profLiga360/profSeo зникли зі словника й коду", () => {
  for (const k of ["tagsField", "tagsPh", "tagsEditTitle", "tagsSave", "tagsBad"]) {
    for (const lang of ["uk", "en"]) assert.equal(typeof DICT[lang][k], "string", `${lang}.${k}`);
  }
  /* Кнопки «Мітки» на картці нема (меню картки): ключі `thTagsEdit`/`thTagsEditAria` прибрано разом із нею. */
  for (const k of ["thTagsEdit", "thTagsEditAria"]) for (const lang of ["uk", "en"]) assert.equal(DICT[lang][k], undefined, `${lang}.${k}`);
  for (const k of ["profUnited", "profLiga360", "profSeo"]) {
    assert.equal(DICT.uk[k], undefined, `uk.${k}`);
    assert.equal(DICT.en[k], undefined, `en.${k}`);
    for (const f of jsFiles()) assert.ok(!readSource(f).includes(k), `${k} лишився в ${f}`);
  }
});
