/**
 * Забілити коментарі перед скануванням сирця.
 *
 * Потрібно тому, що в цьому репозиторії коментарі — головна документація, і
 * заборонені слова стоять у них законно (`getComputedStyle` у поясненні, чому
 * його тут не кличуть; `&amp;` у поясненні, що саме екранується). Охоронець,
 * який валиться на власному поясненні, змушує пояснення не писати.
 *
 * ⚠️ НЕ плутати з `blankComments` у `tests/i18n-literals.test.mjs`: там
 * коментарі забілюються ЗІ ЗБЕРЕЖЕННЯМ ДОВЖИНИ, бо далі по сирцю рахуються
 * позиції літералів. Тут довжина не зберігається, зате результат придатний
 * для простого `match`/`includes`. Дві різні вимоги, тому й дві функції —
 * і саме тому друга лишилась у своєму тесті, а не переїхала сюди вдавати
 * спільну.
 */
export const stripComments = (src) =>
  src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/[^\n]*/g, "$1 ");
