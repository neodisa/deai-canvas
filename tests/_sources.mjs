import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

/** Корінь коду, який стережуть охоронці. */
export const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "app");

/**
 * Рекурсивний обхід дерева. Шляхи — ВІДНОСНО `APP`, прямим слешем
 * (`vendor/insp-report.js`): саме ними адресуються винятки в тестах і саме так
 * вони читаються в повідомленні про падіння.
 *
 * Сортування — на КОЖНОМУ рівні, тобто перелік не залежить від порядку, у
 * якому файли віддає файлова система: інакше падіння називало б файли щоразу
 * в іншому порядку, а підлоги-свідки лишились би однаковими, і різницю між
 * прогонами довелось би списувати на випадковість.
 *
 * Розширення фільтрують ЛИСТЯ, не теки: у теку заходимо завжди. Інакше
 * `app/vendor/` (де немає нічого, крім `.js`) було б відкинуто разом із
 * `app/__pycache__` — тобто рівно та сама сліпота, лише зроблена акуратно.
 */
function walk(dir, exts, base = "") {
  const out = [];
  const ents = readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const e of ents) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(path.join(dir, e.name), exts, rel));
    else if (exts.some((x) => e.name.endsWith(x))) out.push(rel);
  }
  return out;
}

/** Усі `.js` під `app/`. */
export const jsFiles = (dir = APP) => walk(dir, [".js"]);

/** Усі `.js` і `.css` під `app/` — для охоронця керуючих байтів: він питає не
 *  про авторство тексту, а про те, чи лишається файл ТЕКСТОМ для наших
 *  інструментів, а це властивість і таблиці стилів теж. */
export const sourceFiles = (dir = APP) => walk(dir, [".js", ".css"]);

