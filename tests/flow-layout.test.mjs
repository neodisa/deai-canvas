test("pos row 0 не сідає ПОВЕРХ автовузла тієї ж колонки", () => {
  /* Найзвичайніший жест руками: потягнути вузол на самий верх його колонки.
     `rowAt` дає для нього row 0 — а нульовий ряд уже займає автовузол, який
     стоїть у тій колонці за рангом. Розкладка, що просто рахує «зверху нічого
     немає → y = 0» (як стояло в плані), кладе два кадри в одну точку: обидва
     виходять з y = 0, і один навсправжки ХОВАЄТЬСЯ під другим. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "b", pos: { col: 0, row: 0 } }],
    edges: [], ranks: new Map([["a", 0], ["b", 0]]) }], () => 50, OPTS);
  const [A, B] = ["a", "b"].map((id) => bands[0].placed.find((p) => p.id === id));
  assert.equal(B.y, 0, "руками поставлений вузол забирає нульовий ряд");
  assert.equal(A.y, 80, "автовузол зсувається під нього, а не лишається під ним");
  assert.notEqual(A.y, B.y);
});

test("завеликий row кладе вузол у хвіст колонки, а не роздуває її", () => {
  /* `flow.json` пишуть руками, тож `row: 9999` цілком реальний. Ряд — це
     ПОЗИЦІЯ в колонці: за хвостом позиції немає, отже вузол стає останнім.
     Реалізація, що добивала колонку порожніми рядами до `row` (як у плані),
     на такому числі роздувала масив на мільйони записів і вішала вкладку. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "b", pos: { col: 0, row: 1e9 } }, { id: "c" }],
    edges: [], ranks: new Map([["a", 0], ["b", 0], ["c", 0]]) }], () => 50, OPTS);
  const [A, B, C] = ["a", "b", "c"].map((id) => bands[0].placed.find((p) => p.id === id));
  assert.equal(A.y, 0);
  assert.equal(C.y, 80, "автовузол не чекає на порожні ряди перед собою");
  assert.equal(B.y, 160, "хвіст колонки, а не мільярд порожніх рядів");
  assert.equal(bands[0].contentH, 220, "смуга не виросла на порожнє місце");
});

test("непридатний pos падає з назвою вузла — як і непридатний ранг", () => {
  // Той самий рядок думки, що вище на рангу й висоті: кривий кадр на канвасі
  // гірший за помилку, яка називає вузол. Джерело числа в тексті РІЗНЕ, бо
  // виправляти доводиться різні місця: ранг рахує граф, `pos` пишуть руками.
  const posBand = (pos) => flowLayout([{ id: "f", nodes: [{ id: "a", pos }],
    edges: [], ranks: new Map([["a", 0]]) }], () => 50, OPTS);
  assert.throws(() => posBand({ col: 1.5, row: 0 }), /вузол a: pos.col 1.5 непридатний/);
  assert.throws(() => posBand({ col: -2, row: 0 }), /вузол a: pos.col -2 непридатний/);
  assert.throws(() => posBand({ col: 0, row: -1 }), /вузол a: pos.row -1 непридатний/);
  assert.throws(() => posBand({ col: 0, row: 1.5 }), /вузол a: pos.row 1.5 непридатний/);
});

/* --- жодне ребро не проходить через ЧУЖИЙ кадр (перевірка зі спеки) --- */

/**
 * Семпл точок по шляху кожного ребра проти прямокутників УСІХ кадрів смуги.
 * Повертає перелік влучань «ребро → кадр» із першою точкою всередині — перелік, а
 * не «є перетин»: інакше з падіння не видно, яка саме лінія і в який кадр зайшла.
 *
 * Межа кадру — НЕ «крізь»: пряме ребро законно ПОЧИНАЄТЬСЯ на правому краї
 * джерела й КІНЧАЄТЬСЯ на лівому краї цілі, а стояк лейна виходить із нижнього
 * краю. Тому всередині рахуємо СТРОГО (`>`/`<`), інакше кожне справне ребро
 * читалось би як перетин.
 *
 * Крок 1px: стояк, що зачепив кадр на два пікселі, читається так само криво, як
 * той, що прокреслив його навиліт, і побачити треба обидва.
 */
function crossings(band, step = 1) {
  const hits = new Map();            // «ребро|кадр» → перше влучання
  for (const e of band.edges) {
    for (let i = 1; i < e.points.length; i += 1) {
      const [x1, y1] = e.points[i - 1];
      const [x2, y2] = e.points[i];
      const n = Math.max(1, Math.ceil(Math.hypot(x2 - x1, y2 - y1) / step));
      for (let k = 0; k <= n; k += 1) {
        const x = x1 + ((x2 - x1) * k) / n;
        const y = y1 + ((y2 - y1) * k) / n;
        for (const p of band.placed) {
          if (x > p.x && x < p.x + p.w && y > p.y && y < p.y + p.h) {
            const at = `${e.from} → ${e.to}|${p.id}`;
            if (!hits.has(at)) {
              hits.set(at, `ребро ${e.from} → ${e.to}: точка (${Math.round(x)}, ${Math.round(y)})`
                + ` всередині кадру ${p.id} [${p.x}..${p.x + p.w}]×[${p.y}..${p.y + p.h}]`);
            }
          }
        }
      }
    }
  }
  return [...hits.values()];
}

test("сама перевірка перетинів вміє ловити — і не бачить перетину там, де межа", () => {
  /* Найгірший можливий результат тут — семпл, який не знаходить нічого й
     назавжди лишається зеленим. Тому спершу підсунутий наскрізний шлях. */
  const frame = { id: "a", x: 0, y: 0, w: 100, h: 60 };
  assert.equal(crossings({ placed: [frame],
    edges: [{ from: "x", to: "y", points: [[50, -20], [50, 100]] }] }).length, 1);
  // А шлях по самій межі — не «крізь»: справне ребро законно стоїть на краї кадру.
  assert.deepEqual(crossings({ placed: [frame],
    edges: [{ from: "x", to: "y", points: [[100, 30], [200, 30]] }] }), []);
  assert.deepEqual(crossings({ placed: [frame],
    edges: [{ from: "x", to: "y", points: [[50, 60], [50, 200]] }] }), [],
    "стояк лейна виходить із нижнього краю — це не перетин");
});

test("на однорядних колонках ні пряме, ні довге ребро в кадри не заходять", () => {
  const { bands } = band(
    [{ id: "a" }, { id: "b" }, { id: "c" }],
    [{ from: "a", to: "b" }, { from: "b", to: "c" }, { from: "a", to: "c" }],
    { a: 0, b: 1, c: 2 });
  assert.deepEqual(crossings(bands[0]), []);
});

test("ребро між вузлами ОДНІЄЇ колонки не креслить кадр навиліт", () => {
  /* Найзвичайніший жест дизайнера: поставити два звʼязані вузли один під одним.
     `pos` перебиває ранг, тож колонки стають РІВНІ — а розвилка розкладки знала
     лише «сусідні» (`b.col - a.col === 1`) проти «всього іншого», і рівність
     падала в гілку лейна: поперечка виходила нульової довжини, а стояк повертався
     в ціль ТИМ САМИМ `x`, тобто крізь усе тіло кадру-джерела.

     Живий прогін ревʼю: кадри n1 x=1376 y=1030..1964, n2 x=1376 y=0..934, ребро
     [[2016,1964],[2016,2060],[2016,2060],[2016,934]] — останній відрізок ішов
     2060 → 934 наскрізь через n1. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "n1", pos: { col: 1, row: 1 } }, { id: "n2" }],
    edges: [{ from: "n1", to: "n2" }],
    ranks: new Map([["n1", 0], ["n2", 1]]) }], () => 50, OPTS);
  const [N2, N1] = ["n2", "n1"].map((id) => bands[0].placed.find((p) => p.id === id));
  assert.equal(N1.x, N2.x, "перевірка нічого не варта, якщо колонки не рівні");
  assert.ok(N1.y > N2.y, "ціль мусить стояти ВИЩЕ за джерело — саме цей випадок");
  assert.deepEqual(crossings(bands[0]), []);
});

test("та сама колонка, але ціль НИЖЧЕ джерела — і теж без перетину", () => {
  // Нульова колонка окремо: ліворуч від неї зазору немає, і стояк мусить піти
  // в зазор ПРАВОРУЧ, а не за лівий край світу.
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "b", pos: { col: 0, row: 1 } }],
    edges: [{ from: "a", to: "b" }],
    ranks: new Map([["a", 0], ["b", 1]]) }], () => 50, OPTS);
  const [A, B] = ["a", "b"].map((id) => bands[0].placed.find((p) => p.id === id));
  assert.equal(A.x, 0);
  assert.equal(B.x, 0, "обидва в нульовій колонці");
  assert.deepEqual(crossings(bands[0]), []);
  for (const e of bands[0].edges) {
    for (const [x] of e.points) assert.ok(x >= 0, `точка ребра поїхала за лівий край: ${x}`);
  }
});

test("двом ребрам в одній колонці — різні стояки, вони не злипаються в одну лінію", () => {
  /* Та сама причина, що в лейнів під смугою: дві лінії на одному `x` читаються
     як одна, і читач не бачить, скільки насправді переходів. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "b", pos: { col: 1, row: 0 } },
            { id: "c", pos: { col: 1, row: 1 } }, { id: "d", pos: { col: 1, row: 2 } }],
    edges: [{ from: "b", to: "c" }, { from: "c", to: "d" }],
    ranks: new Map([["a", 0], ["b", 1], ["c", 2], ["d", 3]]) }], () => 50, OPTS);
  const xs = bands[0].edges.map((e) => e.points[1][0]);
  assert.equal(new Set(xs).size, 2, `стояки мусять бути різні: ${xs}`);
  assert.deepEqual(crossings(bands[0]), []);
});

/** `x` кожного стояка смуги: вертикальні відрізки шляхів, тобто ті, де x не змінився. */
function stalks(band) {
  const out = [];
  for (const e of band.edges) {
    for (let i = 1; i < e.points.length; i += 1) {
      const [x1, y1] = e.points[i - 1];
      const [x2, y2] = e.points[i];
      if (x1 === x2 && y1 !== y2) out.push(x1);
    }
  }
  return out;
}

test("стояки двох РІЗНИХ ребер не злипаються в одну лінію — навіть в одному зазорі", () => {
  /* Зазор між колонками 0 і 1 — ОДНЕ місце смуги, хоч для колонки 0 він «правий»,
     а для колонки 1 «лівий». Лічильник стояків, ключений КОЛОНКОЮ (як стояло в
     розкладці), давав обом ребрам k = 0, тобто той самий `x` = 110: дві лінії
     читались як одна, і читач не бачив, скільько насправді переходів. Тому ключ —
     зазор, а не колонка. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "z", pos: { col: 0, row: 1 } },
            { id: "b", pos: { col: 1, row: 0 } }, { id: "y", pos: { col: 1, row: 1 } }],
    edges: [{ from: "a", to: "z" }, { from: "b", to: "y" }],
    ranks: new Map([["a", 0], ["z", 0], ["b", 1], ["y", 1]]) }], () => 50, OPTS);
  const xs = stalks(bands[0]);
  assert.equal(xs.length, 2, `стояків мусить бути два: ${xs}`);
  assert.equal(new Set(xs).size, 2, `стояки в спільному зазорі злиплись: ${xs}`);
  assert.deepEqual(crossings(bands[0]), []);
});

test("зворотні ребра теж не заходять у кадри, і їхні стояки не злипаються", () => {
  /* Зворотне ребро (`b.col < a.col`) досяжне драгом: досить перетягнути ціль
     ЛІВІШЕ за джерело. Через одну колонку назад обидва стояки такого ребра
     потрапляють в ОДИН зазор, тож перевіряти треба і перетини, і злипання.
     Колонки тут багаторядні — саме на них старий спуск із-під центру і креслив
     сусіда навиліт. */
  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "z" }, { id: "b" }, { id: "y" }, { id: "c" }],
    edges: [{ from: "a", to: "b" }, { from: "b", to: "c" },
            { from: "c", to: "a" }, { from: "b", to: "a" }],
    ranks: new Map([["a", 0], ["z", 0], ["b", 1], ["y", 1], ["c", 2]]) }], () => 50, OPTS);
  assert.deepEqual(crossings(bands[0]), []);
  const xs = stalks(bands[0]);
  assert.equal(xs.length, 4, `у двох зворотних ребер чотири стояки: ${xs}`);
  assert.equal(new Set(xs).size, 4, `стояки злиплись: ${xs}`);
  for (const [x] of bands[0].edges.flatMap((e) => e.points)) {
    assert.ok(x >= 0, `точка ребра поїхала за лівий край: ${x}`);
  }
});

