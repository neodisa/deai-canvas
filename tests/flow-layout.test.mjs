  const { bands } = flowLayout([{ id: "f",
    nodes: [{ id: "a" }, { id: "c" }, { id: "b", pos: { col: 0, row: 1 } }],
    edges: [], ranks: new Map([["a", 0], ["b", 0], ["c", 0]]) }], () => 50, OPTS);
  const [A, B, C] = ["a", "b", "c"].map((id) => bands[0].placed.find((p) => p.id === id));
  assert.equal(A.y, 0);
  assert.equal(B.y, 80, "row 1 = свій ряд, хоч описаний вузол третім");
  assert.equal(C.y, 160, "автовузол обходить руками поставлений, а не лізе під нього");
