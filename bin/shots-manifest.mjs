/**
 * Манифест знімків ітерації — розписка, а не кеш. Він відповідає на три питання:
 * якого розміру кадр (щоб канвас не міряв iframe), чи знімок відстав від макета
 * (`stamp`), і чи сторінка взагалі встояла на час затвора (`stable`).
 *
 * Час приходить ЗЗОВНІ (`now`), щоб функції були чистими й тестованими.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

export const CONTRACT =
  "Знімки сторінок ітерації для канваса. Кадр = знімок URL /commented?…&bare=1 у вьюпорті 1280. " +
  "`stamp` — хеш файлів сторінки й shared/: розійшовся з поточними файлами → кадр застарів, і канвас каже це вголос. " +
  "`sha` — хеш САМИХ БАЙТІВ кадру; з нього канвас будує ключ вічного кешу (`shotVersion` у app/flow-model.js). " +
  "`stable: false` означає, що сторінка не дала двох однакових знімків, тобто вона ще рухалась і кадру вірити не можна. " +
  "`problem` — причина, з якої кадру вірити не можна (порожня сторінка, дірки в картинках, сторінка не встояла). " +
  "Запис із `problem` завжди застарілий: наступний прогін зʼємки перезніме його без прапорців.";

/**
 * Хеш байтів кадру — перші 16 hex sha-256.
 *
 * Це ЄДИНА частина ключа кадру, яка міняється від самої перезйомки. `stamp`
 * хешує ДЖЕРЕЛА (перезнім при незмінних файлах його не рухає), а `capturedAt`
 * має точність до ХВИЛИНИ — дві зйомки в одну хвилину дають однакову мітку.
 * Разом це давало ідентичний URL при різних байтах, а `/shot` віддається з
 * `immutable, max-age=31536000`: браузер рік показував би старий кадр. Найгірше
 * складалось так: «Перезняти» → кадр битий → «Перезняти» ще раз через 10 секунд
 * → `problem` зникає з манифеста, бейдж гасне, а в `<img>` висить СТАРИЙ битий
 * знімок. Полотно каже «все гаразд» над несвіжим кадром.
 *
 * Хеш байтів, а не мітка часу з секундами: ключ описує САМЕ ТЕ, що віддається.
 * Побічний виграш — перезйомка, яка дала ті самі байти (звичайна річ: сторінка
 * не мінялась), лишає ключ тим самим і не викидає з кешу цілий екран кадрів.
 *
 * 16 hex = 64 біти. Кадрів в ітерації десятки, отже колізія неможлива на
 * практиці, а манифест лишається читним очима.
 */
export function shotSha(buf) {
  return createHash("sha256").update(buf).digest("hex").slice(0, 16);
}

export function shotsDir(iterDir) {
  return path.join(iterDir, "shots");
}

export function manifestPath(iterDir) {
  return path.join(shotsDir(iterDir), "manifest.json");
}

export function readManifest(iterDir) {
  const empty = { contract: CONTRACT, checkedAt: null, shots: {} };
  try {
    return { ...empty, ...JSON.parse(readFileSync(manifestPath(iterDir), "utf8")) };
  } catch {
    // Нечитний манифест (немає файлу, обрізаний JSON, помилка доступу) вважаємо
    // відсутнім: весь вміст стане stale, кадри перезнімуться. Це безпечна сторона
    // помилки, протилежна тому, щоб закодувати брехню в маніместі.
    return empty;
  }
}

let writeSeq = 0;

export function writeManifest(iterDir, manifest) {
  mkdirSync(shotsDir(iterDir), { recursive: true });
  const body = JSON.stringify({ ...manifest, contract: CONTRACT }, null, 2);
  // Запис через тимчасовий файл: манифест лежить у справжній теці макетів, а
  // зʼємку можуть убити посеред довгого браузерного прогону — обрізаний JSON
  // втратив би накопичені метадані всіх сторінок, не лише тієї, що знімалась.
  // Власне імʼя на КОЖЕН запис. Спільне `manifest.json.tmp` зводило атомарність
  // нанівець: два прогони зʼємки (чи прогін і `--check`) відкривали один шлях,
  // обрізали одне одного, і rename атомарно клав на місце вже зіпсоване. Той
  // самий висновок, що в `_flow_save` на боці Python. pid розводить процеси,
  // лічильник — записи всередині одного процесу.
  // ⚠️ Режим цілі тут НЕ зберігається, на відміну від Python-боку
  // (`atomic_io.atomic_write_json`): манифест — похідний артефакт зʼємки, його
  // ніхто не носить руками й не виносить симлінком. Не шукай симетрії, якої
  // свідомо немає.
  const tmp = `${manifestPath(iterDir)}.${process.pid}.${++writeSeq}.tmp`;
  try {
    writeFileSync(tmp, `${body}\n`, "utf8");
    renameSync(tmp, manifestPath(iterDir));
  } catch (e) {
    // Невдача не сміє лишати сміття — і саме унікальне імʼя робить це критичним:
    // спільний `manifest.json.tmp` наступний прогін просто перезаписував, а
    // тепер КОЖЕН убитий прогін лишав би НОВИЙ файл. Кожен такий недоносок
    // зсуває mockup_hash і їде колегам у спільне репо. Той самий клас, що вже
    // закритий у serve.atomic_write_json — асиметрії між боками бути не мусить.
    try {
      rmSync(tmp, { force: true });
    } catch {
      // Прибирання — best-effort: причина початкової невдачі важливіша за
      // причину невдалого прибирання, і саме її ми кидаємо далі.
    }
    throw e;
  }
}

/**
 * Id, які треба знімати: немає знімка, немає штампа, штамп розійшовся — або
 * кадр записаний із проблемою.
 *
 * Проблема робить кадр застарілим ЗА ПОБУДОВОЮ, і це не зручність. Кадр із
 * порожньою сторінкою чи дірками записувався зі свіжим штампом, тобто
 * інкрементальний прогін вважав його актуальним і не чіпав ніколи: самолікування
 * конвеєра було зламане рівно там, де воно найпотрібніше. Перезняти можна було
 * тільки `--all` і тільки знаючи, що треба.
 */
export function staleIds(manifest, stamps) {
  const shots = manifest.shots ?? {};
  return Object.keys(stamps).filter((id) => {
    const shot = shots[id];
    return !shot || !shot.stamp || shot.stamp !== stamps[id] || Boolean(shot.problem);
  });
}

/**
 * Позначити застарілі й записати, коли перезважували. Запис сторінки, якої вже
 * немає в дереві, іде геть: інакше манифест роками носив би кадри видалених
 * сторінок і рахував їх у звітах.
 *
 * ПЕРЕДУМОВА: `stamps` — ПОВНИЙ і достовірний перелік поточних КЛЮЧІВ КАДРІВ.
 * Кожен запис, чийого id тут немає, вважається зниклим і зникає з манифеста
 * назавжди. Той, хто кличе цю функцію, відповідає за те, щоб не передати сюди
 * усічений перелік — порожній, частковий, або добраний із будь-якого джерела,
 * яке не охоплює ВСІ поточні кадри. Інакше манифест забуде метадані (`stamp`,
 * `w`, `h`, `bytes`, `capturedAt`) для кадрів, які насправді на місці, хоча
 * `.webp` файли їх знімків лишаться на диску.
 *
 * ⚠️ «Кадрів», а не «сторінок», і це не педантизм. Ключ кадру — це сторінка
 * ПЛЮС стан (`сторінка~хеш`) ПЛЮС ширина (`сторінка@390`), тобто одна сторінка
 * дає кілька кадрів. Поки тут стояло «сторінок», найприродніша реалізація
 * вьюпортів — «рахувати штампи для ширини, яку знімаємо» — виглядала як
 * виконання цієї передумови, а насправді стирала кадри двох інших ширин.
 * Доведено мутацією на `stampsFor` (01.09.2026): десктопний запис зникав із
 * манифеста після прогону мобайла, а `.webp` лишався сиротою на диску.
 *
 * Оновлює ЛИШЕ наявні записи `manifest.shots` — сторінку, яку ще ніколи не знімали,
 * ця функція записом не заводить (ні `stale: true`, ні порожнім). Створення запису —
 * відповідальність зʼємки (`runShoot`), не перевірки: кадр з'являється в манифесті
 * разом зі знімком, а не з фактом його застарівання.
 */
export function markStale(manifest, stamps, now) {
  const stale = new Set(staleIds(manifest, stamps));
  const shots = {};
  for (const [id, shot] of Object.entries(manifest.shots ?? {})) {
    if (!(id in stamps)) continue;
    shots[id] = { ...shot, stale: stale.has(id) };
  }
  return { ...manifest, checkedAt: now, shots };
}
